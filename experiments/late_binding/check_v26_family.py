#!/usr/bin/env python3
"""v26: the primary family of Part B computed a second time, without the report's code.

Reads fault_rate_runs.csv and masks_v26.json, computes the 24 tests as results_v26_faults/PREREGISTRATION.md defines them (for each
size and rate: CI_heurLA_X_LF against the best reference in THR and in LAT at 1.0 x Lsat; unit = mask; Holm over all tests), and compares
effect, interval, p, Holm-adjusted p and verdict with report/primary.csv (written by report_v26.py). Nothing of report_v26.py is
imported: the load at 1.0 x Lsat is taken as the second of the four loads of a cell, the size and the rate of a mask from masks_v26.json.

usage: python3 check_v26_family.py      (V26_RES overrides the results directory)
Writes report/families_check.md; exit status 1 if a test differs.
"""
import csv
import json
import math
import os
import sys
from collections import defaultdict

from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.environ.get('V26_RES', os.path.join(HERE, 'results_v26_faults'))
TOL = 0.006       # percentage points (the report rounds to 0.01)
RTOL = 2e-3       # relative, p values (the report writes four significant digits)
MAIN = 'CI_heurLA_X_LF'
REFS = ['DeFT_P', 'DeFT_B', 'DeFT_Dis', 'DeFT_Ran']
NL = chr(10)


def main():
    rate_of = {(e['size'], e['mask']): e['rate'] for e in json.load(open(os.path.join(RES, 'masks_v26.json')))['part_b']}
    cell = defaultdict(dict)       # (size, mask, traffic, row, seed) -> {rate: run}
    with open(os.path.join(RES, 'fault_rate_runs.csv')) as fh:
        rows = list(csv.DictReader(fh))
    for r in rows:
        size, traffic = r['pattern'].split('-', 1)
        cell[(size, r['mask'], traffic, r['variant'].rsplit('-p', 1)[0], int(r['seed']))][float(r['rate'])] = r
    assert {len(v) for v in cell.values()} == {4}, 'a cell does not have four loads'
    seeds = sorted({k[4] for k in cell})
    traffics = sorted({k[2] for k in cell})
    masks = defaultdict(list)      # (size, rate) -> masks, as they appear
    for (size, mask, _, _, _) in cell:
        if mask not in masks[(size, rate_of[(size, mask)])]:
            masks[(size, rate_of[(size, mask)])].append(mask)

    def metric(size, mask, traffic, row, seed, what):
        c = cell.get((size, mask, traffic, row, seed))
        if not c:
            return None
        if what == 'THR':
            return max(float(x['accepted']) for x in c.values())
        return float(c[sorted(c)[1]]['latency'])

    def best(size, mask, traffic, what):
        cand = []
        for ref in REFS:
            v = [metric(size, mask, traffic, ref, s, what) for s in seeds]
            if all(x is not None for x in v):
                cand.append((sum(v) / len(v), ref))
        return (max(cand) if what == 'THR' else min(cand))[1]

    mine = {}
    for (size, rate), ms in sorted(masks.items()):
        for what in ('THR', 'LAT'):
            vm = []
            for mask in ms:
                acc = []
                for traffic in traffics:
                    ref = best(size, mask, traffic, what)
                    for s in seeds:
                        a, b = metric(size, mask, traffic, MAIN, s, what), metric(size, mask, traffic, ref, s, what)
                        if a is not None and b is not None:
                            acc.append(math.log(a / b))
                vm.append(sum(acc) / len(acc))
            n = len(vm)
            m = sum(vm) / n
            se = math.sqrt(sum((x - m) ** 2 for x in vm) / (n - 1)) / math.sqrt(n)
            h = stats.t.ppf(0.975, n - 1) * se
            p = 2 * stats.t.sf(abs(m / se), n - 1)
            mine[(size, rate, what)] = [100 * (math.exp(m) - 1), 100 * (math.exp(m - h) - 1), 100 * (math.exp(m + h) - 1), p, n]
    keys = sorted(mine)
    order = sorted(range(len(keys)), key=lambda i: mine[keys[i]][3])
    run = 0.0
    for rank, i in enumerate(order):
        run = max(run, min(1.0, (len(keys) - rank) * mine[keys[i]][3]))
        k = keys[i]
        mine[k] += [run, 'n.s.' if run >= 0.05 else ('supported' if (mine[k][0] > 0) == (k[2] == 'THR') else 'against')]

    rep = {(r['size'], r['rate'], r['metric']): r for r in csv.DictReader(open(os.path.join(RES, 'report', 'primary.csv')))}
    L = ['# v26: the primary family of Part B computed a second time (generated by check_v26_family.py)', '',
         'The %d tests of `PREREGISTRATION.md` computed from `fault_rate_runs.csv` by a script that shares no code with `report_v26.py`, and compared with' % len(mine),
         '`report/primary.csv` (effect, 95 % interval, p, Holm-adjusted p, verdict).', '',
         '* %d runs; %s; seeds %s; traffic %s.' % (len(rows), ', '.join('%s %s: %d masks' % (z, r, len(v)) for (z, r), v in sorted(masks.items())), seeds, traffics)]
    bad, worst = 0, 0.0
    for k in keys:
        e, lo, hi, p, n, ph, v = mine[k]
        b = rep.get(k)
        if b is None:
            bad += 1
            L.append('* MISSING in the report: %s' % ' '.join(k))
            continue
        d = max(abs(e - float(b['effect_pct'])), abs(lo - float(b['ci_low'])), abs(hi - float(b['ci_high'])))
        worst = max(worst, d)
        same = (d < TOL and abs(p - float(b['p'])) <= RTOL * float(b['p']) and abs(ph - float(b['p_holm'])) <= RTOL * float(b['p_holm']) and v == b['verdict'] and n == int(b['n_masks']))
        bad += not same
        if not same:
            L.append('* DIFFERENT %s: second computation %.2f [%.2f, %.2f] p %.4g Holm %.4g %s (%d masks); report %s [%s, %s] p %s Holm %s %s (%s masks)' % (
                ' '.join(k), e, lo, hi, p, ph, v, n, b['effect_pct'], b['ci_low'], b['ci_high'], b['p'], b['p_holm'], b['verdict'], b['n_masks']))
    L += ['* **Primary family: %d tests, %d different.** Largest difference of an effect or of an interval end: %.4f percentage points (the report rounds to 0.01); verdicts: %s.' % (
        len(keys), bad, worst, ', '.join('%d %s' % (sum(1 for x in mine.values() if x[6] == v), v) for v in ('supported', 'against', 'n.s.'))), '',
          '**All compared tests agree: %s.**' % ('yes' if bad == 0 and len(rep) == len(mine) else 'NO'), '']
    os.makedirs(os.path.join(RES, 'report'), exist_ok=True)
    with open(os.path.join(RES, 'report', 'families_check.md'), 'w', newline=NL) as fh:
        fh.write(NL.join(L))
    print(NL.join(L))
    return 1 if bad or len(rep) != len(mine) else 0


if __name__ == '__main__':
    sys.exit(main())
