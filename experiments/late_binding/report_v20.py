"""Analysis of v20 (Part L), following results_v20_delay/PREREGISTRATION.md (descriptive).

Usage: python3 report_v20.py
results_v20_delay/delay_runs.csv, results_v19_vnrr/eval_runs.csv (N = 0 and the reference), load_points_rr.json
-> report/effects.csv, stop_points.csv, multi_output_share.csv, summary.md, delay_effects.{png,pdf}
"""
import csv
import json
import os

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt  # noqa: E402

from report_v4 import Data, load_csv, pct  # noqa: E402
import experiments_v5 as E5  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, 'results_v20_delay')
K = os.path.join(HERE, 'results_v19_vnrr')
OUT = os.path.join(RES, 'report')
SIZES = ['2x2', '3x3', '4x4']
VARIANTS = ['CI_heurLA_G', 'CI_qlLA_G', 'FULL_qlLA_G']
DELAYS = [0, 1, 2, 4]
SEEDS = range(61, 66)
METRICS = ['LAT', 'P99', 'THR']
NL = chr(10)


def scen(z):
    return [(f'{z}-uniform', E5.FREE[z]), (f'{z}-hotspot', E5.FREE[z]), (f'{z}-chipperm', E5.FREE[z]), (f'{z}-uniform', E5.NORTH[z])]


def write(path, rows):
    with open(path, 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator=NL)
        w.writeheader()
        w.writerows(rows)


def beats(x):
    return x['ci_low'] > 0 if x['metric'] == 'THR' else x['ci_high'] < 0


def main():
    os.makedirs(OUT, exist_ok=True)
    P = json.load(open(os.path.join(K, 'load_points_rr.json')))

    def ladder(p, m):
        size, pat = p.split('-')
        return P[f'{size}__{pat}__{m}']['eval']
    K5 = load_csv(os.path.join(K, 'eval_runs.csv'))
    R = {('DeFT', p, m, r, s): x for (v, p, m, r, s), x in K5.items() if v == 'DeFT'}
    R.update({(f'{v}-N0', p, m, r, s): x for (v, p, m, r, s), x in K5.items() if v in VARIANTS})
    runs = list(csv.DictReader(open(os.path.join(RES, 'delay_runs.csv'))))
    for r in runs:
        R[(f'{r["variant"]}-N{r["delay"]}', r['pattern'], r['mask'], float(r['rate']), int(r['seed']))] = dict(
            latency=float(r['latency']), p99=float(r['p99']), accepted=float(r['accepted']))
    D = {z: Data(R, scen(z), ladder, SEEDS) for z in SIZES}

    eff = []
    for z in SIZES:
        for v in VARIANTS:
            for n in DELAYS:
                for name in METRICS:
                    xs = D[z].per_seed(f'{v}-N{n}', 'DeFT', name)
                    e, lo, hi = pct(xs)
                    eff.append(dict(size=z, variant=v, delay=n, metric=name, n_seeds=len(xs), effect_pct=round(e, 2), ci_low=round(lo, 2), ci_high=round(hi, 2)))
    write(os.path.join(OUT, 'effects.csv'), eff)

    def get(z, v, n, name):
        return next(x for x in eff if (x['size'], x['variant'], x['delay'], x['metric']) == (z, v, n, name))

    def stop(z, v, name):
        return next((str(n) for n in DELAYS if not beats(get(z, v, n, name))), '> 4')
    stops = [dict(size=z, variant=v, metric=name, stops_at=stop(z, v, name)) for z in SIZES for v in VARIANTS for name in ('LAT', 'THR')]
    write(os.path.join(OUT, 'stop_points.csv'), stops)

    share = []
    for z in SIZES:
        for v in VARIANTS:
            rs = [r for r in runs if r['variant'] == v and r['pattern'].startswith(z)]
            for layer, key in (('chiplet', 'chip'), ('interposer', 'ipos')):
                tot = sum(int(r[f'hops_{key}']) for r in rs)
                mul = sum(int(r[f'hops_{key}_multi']) for r in rs)
                share.append(dict(size=z, variant=v, layer=layer, hops=tot, multi_output_hops=mul, share_pct=round(100 * mul / tot, 1) if tot else ''))
    write(os.path.join(OUT, 'multi_output_share.csv'), share)

    expected = len(SIZES) * len(VARIANTS) * 3 * 4 * 7 * len(SEEDS)
    fmt = lambda x: f'{x["effect_pct"]:+.1f} [{x["ci_low"]:+.1f}, {x["ci_high"]:+.1f}]' + (' \\*' if beats(x) else '')  # noqa: E731
    L = ['# v20 summary: decision-delay sensitivity (seeds 61-65; generated by report_v20.py; descriptive)', '',
         f'Runs: {len(runs)} of {expected}; dead-end events: {sum(int(r["dead_ends"]) for r in runs)}. All with -deft_vn_rr 1. N = 0 and the reference DeFT(rho\\*) with round-robin come from K5.', '',
         'Effect = 100 x (exp(mean R) - 1) %, R(s) the mean over the 4 scenarios of the per-seed log ratio against DeFT(rho\\*) with round-robin; 95 % CI over 5 seeds. \\* = beats DeFT (CI entirely on the better side of 0). Negative is better for LAT and P99, positive for THR.', '']
    for name in METRICS:
        L += [f'## {name}' + (' at 1.0 x Lsat' if name != 'THR' else ' (maximum accepted over the 7 loads)'), '', '| size | variant | N = 0 | N = 1 | N = 2 | N = 4 |', '|---|---|---|---|---|---|']
        for z in SIZES:
            for v in VARIANTS:
                L.append(f'| {z} | {v} | ' + ' | '.join(fmt(get(z, v, n, name)) for n in DELAYS) + ' |')
        L.append('')
    L += ['## Smallest N at which the variant stops beating DeFT', '', 'Smallest N of {0, 1, 2, 4} without the \\*; "> 4" if it still beats DeFT at N = 4. With n = 5, a variant can stop through a wide CI alone: read this with the point estimates above.', '',
          '| size | variant | LAT | THR |', '|---|---|---|---|']
    for z in SIZES:
        for v in VARIANTS:
            L.append(f'| {z} | {v} | {stop(z, v, "LAT")} | {stop(z, v, "THR")} |')
    L += ['', '## Share of hops with more than one offered output (runs with N >= 1)', '', '| size | variant | chiplet | interposer |', '|---|---|---|---|']
    for z in SIZES:
        for v in VARIANTS:
            c = [next(x for x in share if (x['size'], x['variant'], x['layer']) == (z, v, y)) for y in ('chiplet', 'interposer')]
            L.append(f'| {z} | {v} | ' + ' | '.join(f'{x["share_pct"]} %' for x in c) + ' |')
    L += ['', 'Figure: `delay_effects.png` / `.pdf`.']
    open(os.path.join(OUT, 'summary.md'), 'w', newline=NL).write(NL.join(L) + NL)

    # effect against N. Hues in the reference categorical order; markers are the secondary encoding.
    series = [('CI_heurLA_G', '#2a78d6', 'o'), ('CI_qlLA_G', '#eb6834', 's'), ('FULL_qlLA_G', '#1baf7a', 'D')]
    plt.rcParams.update({'font.size': 9, 'axes.edgecolor': '#b5b4ad', 'axes.linewidth': 0.8, 'xtick.color': '#52514e', 'ytick.color': '#52514e', 'axes.labelcolor': '#52514e', 'text.color': '#0b0b0b'})
    fig, axes = plt.subplots(2, 3, figsize=(10.5, 5.6), sharex=True)
    for row, name in zip(axes, ('LAT', 'THR')):
        for ax, z in zip(row, SIZES):
            ax.grid(True, color='#e6e5e0', linewidth=0.6)
            ax.set_axisbelow(True)
            ax.axhline(0, color='#52514e', linewidth=1)
            for v, col, mk in series:
                c = [get(z, v, n, name) for n in DELAYS]
                ys = [x['effect_pct'] for x in c]
                err = [[y - x['ci_low'] for x, y in zip(c, ys)], [x['ci_high'] - y for x, y in zip(c, ys)]]
                ax.errorbar(DELAYS, ys, yerr=err, color=col, marker=mk, linewidth=2, markersize=8, markeredgecolor='white', markeredgewidth=1.0, capsize=2, elinewidth=1, label=v)
            ax.set_title(f'{z}, {"mean latency" if name == "LAT" else "throughput"}', fontsize=9.5, loc='left')
            ax.set_xticks(DELAYS)
            for sp in ('top', 'right'):
                ax.spines[sp].set_visible(False)
        row[0].set_ylabel('% against DeFT with round-robin')
    for ax in axes[1]:
        ax.set_xlabel('decision delay N (cycles)')
    h, l = axes[0][0].get_legend_handles_labels()
    fig.legend(h, l, loc='lower center', ncol=3, frameon=False)
    fig.suptitle('Effect of a decision delay (below 0 is better for latency, above 0 for throughput; 95 % CI, 5 seeds)', fontsize=10, x=0.01, ha='left')
    fig.tight_layout(rect=(0, 0.05, 1, 0.96))
    for ext in ('png', 'pdf'):
        fig.savefig(os.path.join(OUT, f'delay_effects.{ext}'), dpi=180)
    plt.close(fig)
    print(NL.join(L))


if __name__ == '__main__':
    main()
