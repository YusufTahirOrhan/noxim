"""v12 (Part D.4): analytical storage and wire cost per router and per packet header, all methods and sizes.

Assumptions (results_v12_energy/DECISIONS.md):
* C chiplets of 16 routers, 4 VLs per chiplet (slot ids: 2 bits); flit 32 bits; packets of 8 flits (synthetic
  traffic); 2 VCs x 4 flits per port; routers with 5 network ports (N, E, S, W, Hub) + local.
* Header fields only count the routing information beyond source and destination ids (chiplet ids follow from those).
* Learned values are stored as 16-bit fixed point (the simulator uses float32; 16 bits is the hardware assumption).
* Occupancy values: 2 VCs x 4 flits -> 0..8, 4 bits.
"""
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'results_v12_energy', 'report')
SIZES = {'2x2': 4, '3x3': 9, '4x4': 16}
SLOT = 2          # bits for one of the 4 VL slots of a chiplet
PORTS = 5         # N, E, S, W, Hub
QBITS = 16
OCC = 4
FLIT = 32
PKT = 8


def rows(C):
    R = 16 * C                     # chiplet routers
    out = []

    def add(method, item, per, bits, note):
        out.append(dict(method=method, item=item, per=per, bits=bits, note=note))
    # header bits
    add('DeFT(rho*), DeFT-Dis, DeFT-Ran, DeFT_OE_G, XY-SP', 'routing header', 'packet', 2 * SLOT,
        'exit and entry VL slot')
    add('MTR', 'routing header', 'packet', 2 * SLOT, 'exit and entry boundary router (slot)')
    add('RC', 'routing header', 'packet', 2 * SLOT, 'exit and entry boundary router (slot)')
    add('CI_*', 'routing header', 'packet', SLOT + 4, 'exit slot + entry candidate mask (4 bits)')
    add('FULL_*', 'routing header', 'packet', 4 + 4, 'exit and entry candidate masks')
    # tables
    add('DeFT(rho*), DeFT_OE_G', 'VL LUT', 'chiplet router', (C - 1) * 2 * SLOT,
        '(C-1) destination chiplets x (exit + entry slot); one fault scenario held')
    add('CI_*', 'exit LUT', 'chiplet router', (C - 1) * SLOT, '(C-1) x exit slot; entry chosen late')
    add('FULL_*', 'VL LUT', 'chiplet router', 0, 'none (both VLs chosen late)')
    add('DeFT-Dis, RC', 'VL choice', 'chiplet router', 0, 'nearest functional VL: comparator logic, no table')
    add('DeFT-Ran', 'VL choice', 'chiplet router', 0, 'random generator, no table')
    add('MTR', 'NI table (destination -> entry boundary router)', 'chiplet router', R * SLOT,
        'MTR paper: per NI, destination id -> boundary router id (16C entries)')
    add('MTR', 'exit boundary router', 'chiplet router', SLOT, 'outbound table entry of the source')
    add('MTR', 'turn restriction bits', 'boundary router', 8, '4 inbound + 4 outbound turn enables')
    add('RC', 'RC buffer', 'boundary router', 4 * PKT * FLIT, '4 packet slots x 8 flits x 32 bits')
    add('RC', 'OPIC request/response wires', 'chiplet', (16 - 4) * 4,
        'one tree per boundary router; 12 tree edges x (2-bit request + 2-bit response)')
    add('RC', 'OPIC permission counters', 'chiplet router', 2 * 3,
        'request and permit counters (3 bits each, up to 4 slots)')
    add('CI_qlLA*, FULL_qlLA*', 'Q table (key: destination chiplet)', 'router with an adaptive choice',
        C * PORTS * QBITS, 'C keys x 5 outputs x 16 bits (CI: interposer routers only; FULL: all routers)')
    add('*_LA (lookahead) and *_qlLA', 'lookahead occupancy wires', 'link direction', PORTS * OCC,
        "the neighbour's downstream occupancy per output (5 x 4 bits)")
    add('*_qlLA', 'learning feedback wires', 'link direction', QBITS, 'value estimate returned on head arrival')
    add('all', 'credit / VC status (reference)', 'link direction', 2 * 3, '2 VCs x 3-bit credit count (baseline router)')
    add('all', 'input buffers (reference)', 'router', (PORTS + 1) * 2 * 4 * FLIT, '6 ports x 2 VCs x 4 flits x 32 bits')
    return out


def main():
    os.makedirs(OUT, exist_ok=True)
    allrows = []
    for z, C in SIZES.items():
        for r in rows(C):
            allrows.append(dict(size=z, **r))
    with open(os.path.join(OUT, 'cost_table.csv'), 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(allrows[0]), lineterminator='\n')
        w.writeheader()
        w.writerows(allrows)
    items = [(r['method'], r['item'], r['per'], r['note']) for r in rows(4)]
    L = ['# Storage and wire cost (analytical; generated by cost_v12.py)', '',
         'Bits per unit. C = number of chiplets; 16 routers and 4 VLs per chiplet; flit 32 bits; 2 VCs x 4 flits per '
         'port. Learned values as 16-bit fixed point. The last two rows give the baseline router for scale.', '',
         '| method | item | per | 2x2 | 3x3 | 4x4 | note |', '|---|---|---|---|---|---|---|']
    for k, (m, it, per, note) in enumerate(items):
        vals = [rows(C)[k]['bits'] for C in SIZES.values()]
        L.append(f'| {m} | {it} | {per} | ' + ' | '.join(str(v) for v in vals) + f' | {note} |')
    open(os.path.join(OUT, 'cost_table.md'), 'w', newline='\n').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
