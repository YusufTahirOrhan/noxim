#!/usr/bin/env python3
"""v27: the primary family of Part C computed a second time, without the report's code.

Reads eval_runs.csv and computes the 18 tests as results_v27_early/PREREGISTRATION.md defines them (for each size and each of EB_vl,
EB_route, EB_down: the main row CI_heurLA_X_LF against that row in THR and in LAT at 1.0 x Lsat; per seed the mean over the scenarios of
the log ratio; one-sample t over the seeds; Holm over all tests), and compares effect, interval, p, Holm-adjusted p and verdict with
report/primary.csv (written by report_v27.py). Nothing of report_v27.py is imported: the load at 1.0 x Lsat is taken as the fourth of
the nine loads of a cell, in increasing order of the rate.

usage: python3 check_v27_family.py      (V27_RES overrides the results directory)
Writes report/families_check.md; exit status 1 if a test differs.
"""
import csv
import math
import os
import sys
from collections import defaultdict

from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.environ.get('V27_RES', os.path.join(HERE, 'results_v27_early'))
TOL = 0.006       # percentage points (the report rounds to 0.01)
RTOL = 2e-3       # relative, p values (the report writes four significant digits)
MAIN = 'CI_heurLA_X_LF'
EARLY = ['EB_vl', 'EB_route', 'EB_down']
NL = chr(10)


def main():
    cell = defaultdict(dict)       # (size, scenario, row, seed) -> {rate: run}
    with open(os.path.join(RES, 'eval_runs.csv')) as fh:
        rows = list(csv.DictReader(fh))
    for r in rows:
        size, scen = r['pattern'].split('-', 1)
        cell[(size, scen, r['variant'].rsplit('-p', 1)[0], int(r['seed']))][float(r['rate'])] = r
    assert {len(v) for v in cell.values()} == {9}, 'a cell does not have nine loads'
    sizes = sorted({k[0] for k in cell})
    scens = sorted({k[1] for k in cell})
    present = sorted({k[2] for k in cell})

    def metric(size, scen, row, seed, what):
        c = cell.get((size, scen, row, seed))
        if not c:
            return None
        if what == 'THR':
            return max(float(x['accepted']) for x in c.values())
        return float(c[sorted(c)[3]]['latency'])

    mine = {}
    for size in sizes:
        for row in EARLY:
            if row not in present:
                continue
            seeds = sorted({k[3] for k in cell if k[0] == size and k[2] == row} & {k[3] for k in cell if k[0] == size and k[2] == MAIN})
            for what in ('THR', 'LAT'):
                per = []
                for s in seeds:
                    acc = [math.log(metric(size, sc, MAIN, s, what) / metric(size, sc, row, s, what)) for sc in scens]
                    per.append(sum(acc) / len(acc))
                n = len(per)
                m = sum(per) / n
                se = math.sqrt(sum((x - m) ** 2 for x in per) / (n - 1)) / math.sqrt(n)
                h = stats.t.ppf(0.975, n - 1) * se
                p = 2 * stats.t.sf(abs(m / se), n - 1)
                mine[(size, row, what)] = [100 * (math.exp(m) - 1), 100 * (math.exp(m - h) - 1), 100 * (math.exp(m + h) - 1), p, n]
    keys = sorted(mine)
    order = sorted(range(len(keys)), key=lambda i: mine[keys[i]][3])
    run = 0.0
    for rank, i in enumerate(order):
        run = max(run, min(1.0, (len(keys) - rank) * mine[keys[i]][3]))
        k = keys[i]
        mine[k] += [run, 'n.s.' if run >= 0.05 else ('supported' if (mine[k][0] > 0) == (k[2] == 'THR') else 'against')]

    rep = {(r['size'], r['early_row'], r['metric']): r for r in csv.DictReader(open(os.path.join(RES, 'report', 'primary.csv')))}
    L = ['# v27: the primary family of Part C computed a second time (generated by check_v27_family.py)', '',
         'The %d tests of `PREREGISTRATION.md` computed from `eval_runs.csv` by a script that shares no code with `report_v27.py`, and compared with' % len(mine),
         '`report/primary.csv` (effect of the main row against the early row, 95 % interval, p, Holm-adjusted p, verdict).', '',
         '* %d runs; sizes %s; scenarios %s; rows %s.' % (len(rows), ', '.join(sizes), ', '.join(scens), ', '.join(present))]
    bad, worst = 0, 0.0
    for k in keys:
        e, lo, hi, p, n, ph, v = mine[k]
        b = rep.get(k)
        if b is None:
            bad += 1
            L.append('* MISSING in the report: %s' % ' '.join(k))
            continue
        d = max(abs(e - float(b['effect_pct'])), abs(lo - float(b['ci_low'])), abs(hi - float(b['ci_high'])))
        worst = max(worst, d)
        same = (d < TOL and abs(p - float(b['p'])) <= RTOL * float(b['p']) and abs(ph - float(b['p_holm'])) <= RTOL * float(b['p_holm']) and v == b['verdict'] and n == int(b['n_seeds']))
        bad += not same
        if not same:
            L.append('* DIFFERENT %s: second computation %.2f [%.2f, %.2f] p %.4g Holm %.4g %s (%d seeds); report %s [%s, %s] p %s Holm %s %s (%s seeds)' % (
                ' '.join(k), e, lo, hi, p, ph, v, n, b['effect_pct'], b['ci_low'], b['ci_high'], b['p'], b['p_holm'], b['verdict'], b['n_seeds']))
    L += ['* **Primary family: %d tests, %d different.** Largest difference of an effect or of an interval end: %.4f percentage points (the report rounds to 0.01); verdicts: %s.' % (
        len(keys), bad, worst, ', '.join('%d %s' % (sum(1 for x in mine.values() if x[6] == v), v) for v in ('supported', 'against', 'n.s.'))), '',
          '**All compared tests agree: %s.**' % ('yes' if bad == 0 and len(rep) == len(mine) else 'NO'), '']
    os.makedirs(os.path.join(RES, 'report'), exist_ok=True)
    with open(os.path.join(RES, 'report', 'families_check.md'), 'w', newline=NL) as fh:
        fh.write(NL.join(L))
    print(NL.join(L))
    return 1 if bad or len(rep) != len(mine) else 0


if __name__ == '__main__':
    sys.exit(main())
