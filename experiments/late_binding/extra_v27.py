"""v27, descriptive tables that FINDINGS.md quotes and report_v27.py does not print (no test, nothing pre-registered):

  python3 extra_v27.py      eval_runs.csv -> report/extra_C.md

  X.1  the counters of C.8 (entry VLs, hops, wait at the source, time to the Up move) and the delivered share of the offered load at
       0.2, 0.5, 0.8 and 1.0 x Lsat: C.8 gives them at 1.0 x Lsat only, where several early rows are past their own saturation
  X.2  the share of the main row's gain over DeFT_P in each scenario (C.2 gives it over the six scenarios)
Definitions as in report_v27.py, whose loader and classes are used.
"""
import json
import os

import report_v27 as RP

MAIN, SCEN, SIZES, SEEDS = RP.MAIN, RP.SCEN, RP.SIZES, RP.C_SEEDS
LOADS = [0, 1, 2, 3]


def main():
    R = RP.load_runs(os.path.join(RP.RES, 'eval_runs.csv'))
    E = RP.Eval(R, json.load(open(os.path.join(RP.R25, 'load_points_v25.json'))), SEEDS)
    rows = E.rows

    def m(row, z, i, f, scen=SCEN):
        v = [x for x in (E.run(row, z, p, i, s) for p in scen for s in SEEDS) if x is not None]
        w = [y for y in (f(x) for x in v) if y is not None]
        return RP.mean(w) if w else None

    def fm(x, form):
        return form % x if x is not None else 'n/a'

    hops = lambda x: (x['hops_chip'] + x['hops_ipos']) / x['packets_measured'] if x.get('hops_chip') is not None and x.get('packets_measured') else None  # noqa: E731
    notdef = lambda x: 100.0 * x['entry_up_not_default'] / x['entry_up_moves'] if x.get('entry_up_moves') else None  # noqa: E731
    wait = lambda x: x.get('entry_inj_wait_mean')  # noqa: E731
    toup = lambda x: x['entry_up_age_mean'] - x['entry_inj_wait_mean'] if x.get('entry_up_age_mean') is not None and x.get('entry_inj_wait_mean') is not None else None  # noqa: E731
    acc = lambda x: x['accepted'] / x['offered'] if x.get('offered') else None  # noqa: E731

    L = ['# v27 Part C: descriptive tables for FINDINGS.md (generated by extra_v27.py; no test, not pre-registered)', '',
         'From `eval_runs.csv` (seeds 161-170). Every number is a mean over the six scenarios and the ten seeds unless a scenario is named.', '',
         '## X.1 The counters of C.8 at the loads up to 1.0 x Lsat', '',
         'Each cell: 0.2 / 0.5 / 0.8 / 1.0 x Lsat of DeFT-P. *delivered*: accepted over offered throughput. *hops*: head-flit forwards per delivered packet (DeFT_P has no',
         'hop counters). *not DeFT-P\'s VL*: share of the Up moves on a VL that is not the LUT\'s entry VL. *imbalance*: the busiest VL (packets Down plus Up) over the mean',
         'VL. *wait*: mean time in the source queue. *to the Up move*: mean time since generation at the Up move less the mean wait; for the injection-time rows the age of',
         'their choice when it takes effect.', '']
    for z in SIZES:
        L += ['### %s' % z, '', '| row | delivered | hops per packet | not DeFT-P\'s VL (%) | imbalance | wait at the source (cycles) | from the injection to the Up move (cycles) |', '|---|---|---|---|---|---|---|']
        for r in rows:
            c = []
            for f, form in ((acc, '%.3f'), (hops, '%.2f'), (notdef, '%.0f'), (lambda x: x.get('vl_imbalance'), '%.2f'), (wait, '%.1f'), (toup, '%.0f')):
                v = [m(r, z, i, f) for i in LOADS]
                c.append('n/a' if all(x is None for x in v) else ' / '.join(fm(x, form) for x in v))
            L.append('| `%s` | %s |' % (r, ' | '.join(c)))
        L.append('')
    L += ['### Hotspot traffic only: from the injection to the Up move (cycles) at 0.2 / 0.5 / 0.8 / 1.0 x Lsat, and delivered at 1.0 x Lsat', '',
          '| size | ' + ' | '.join('`%s`' % r for r in rows if r != 'DeFT_P') + ' |', '|---|' + '---|' * (len(rows) - 1)]
    for z in SIZES:
        L.append('| %s | %s |' % (z, ' | '.join('%s; %s' % (' / '.join(fm(m(r, z, i, toup, ['hotspot']), '%.0f') for i in LOADS), fm(m(r, z, 3, acc, ['hotspot']), '%.3f')) for r in rows if r != 'DeFT_P')))
    L.append('')

    L += ['## X.2 The share of the main row\'s gain over DeFT_P, per scenario', '',
          'Share = (mean over the ten seeds of ln(row / DeFT_P)) / (the same for the main row), in %, THR / LAT at 1.0 x Lsat. 100 = the row gains what the main row gains,',
          '0 = it gains nothing over DeFT_P, negative = it is behind DeFT_P. The second column is the main row\'s own effect against DeFT_P in that scenario; where it is',
          'small (movinghot), the shares are ratios of small numbers.', '']
    new = [r for r in RP.NEW if r in rows]
    for z in SIZES:
        L += ['### %s' % z, '', '| scenario | main row against DeFT_P: THR / LAT | ' + ' | '.join('`%s`' % r for r in new) + ' |', '|---|---|' + '---|' * len(new)]
        for p in SCEN:
            base = {n: RP.tci(E.Rs(MAIN, 'DeFT_P', z, n, [p]))[0] for n in ('THR', 'LAT')}
            c = []
            for r in new:
                s = [100.0 * RP.tci(E.Rs(r, 'DeFT_P', z, n, [p]))[0] / base[n] for n in ('THR', 'LAT')]
                c.append('%.0f / %.0f' % (s[0], s[1]))
            L.append('| %s | %s / %s | %s |' % (p, RP.s1(RP.pct(base['THR'])), RP.s1(RP.pct(base['LAT'])), ' | '.join(c)))
        L.append('')
    # ---- X.3 the main row against DeFT_P: the seeds of round 25 next to the seeds of this round ----
    E25 = RP.Eval(RP.load_runs(os.path.join(RP.R25, 'eval_runs.csv')), E.P, RP.D_SEEDS)
    L += ['## X.3 The main row against DeFT_P on two sets of seeds: round 25 (121-130) and this round (161-170)', '',
          'The same two rows, the same six fault-free scenarios, the same loads and the same definitions; only the seeds differ (and `-deft_lb entry_stats 1`, which only',
          'counts). Effect of the main row against DeFT_P in % with the 95 % interval over the ten seeds of the round. A by-product: the gain of the frozen configuration',
          'on a third set of seeds.', '', '| size | THR: round 25 | THR: this round | LAT at 1.0 x Lsat: round 25 | LAT: this round | P99: round 25 | P99: this round |', '|---|---|---|---|---|---|---|']
    for z in SIZES:
        L.append('| %s | %s |' % (z, ' | '.join(RP.eff(e.group(MAIN, 'DeFT_P', z, n)) for n in ('THR', 'LAT', 'P99') for e in (E25, E))))
    L += ['', 'Per scenario (THR / LAT at 1.0 x Lsat, round 25 -> this round):', '', '| scenario | 2x2 | 3x3 | 4x4 |', '|---|---|---|---|']
    for p in SCEN:
        L.append('| %s | %s |' % (p, ' | '.join('%s / %s -> %s / %s' % tuple(RP.s1(RP.pct(e.group(MAIN, 'DeFT_P', z, n, [p])[0])) for e in (E25, E) for n in ('THR', 'LAT')) for z in SIZES)))
    L.append('')
    RP.wmd('extra_C.md', L)
    print(RP.NL.join(L))


def extra_e():
    """Part E by traffic pattern, next to the same two patterns without faults, and the counters under faults -> report/extra_E.md."""
    f = os.path.join(RP.RES, 'fault_runs.csv')
    if not os.path.exists(f) or sum(1 for _ in open(f)) < 2:
        return
    import report_v26 as RP26
    P = json.load(open(os.path.join(RP.R26, 'load_points_v26.json')))
    ents = [e for e in json.load(open(os.path.join(RP.R26, 'masks_v26.json')))['part_b'] if e['rate'] == '4/16']
    R = RP.load_runs(os.path.join(RP.R26, 'fault_rate_runs.csv'))       # the loader of this round keeps the counter columns
    R.update(RP.load_runs(f))
    lad = lambda e, p: P['%s__%s__%s' % (e['size'], p, e['mask'])]['eval']  # noqa: E731
    D = RP26.Data(R, lad, ents, RP26.PATTERNS, RP26.SEEDS, RP.E_REFS)
    EC = RP.Eval(RP.load_runs(os.path.join(RP.RES, 'eval_runs.csv')), json.load(open(os.path.join(RP.R25, 'load_points_v25.json'))), SEEDS)
    rows = RP.E_ROWS
    eff, pct, s1 = RP.eff, RP.pct, RP.s1

    def share(a, b):
        return '%.0f %%' % (100 * a / b) if b else 'n/a'

    L = ['# v27 Part E: descriptive tables for FINDINGS.md (generated by extra_v27.py; no test, not pre-registered)', '',
         'The design and the definitions of `summary_E.md` (unit = mask, 16 masks per size, rate 4/16, seeds 151 and 152; the reference rows and the main row are the runs',
         'of round 26). `summary_E.md` gives the two traffic patterns together; here they are apart, next to the same two patterns without faults from Part C.', '',
         '## Y.1 Under faults, each traffic pattern separately: against DeFT_P, against the best DeFT variant, and the share of the main row\'s gain over DeFT_P', '',
         '| size | traffic | row | against the main row: THR | LAT | against DeFT_P: THR | LAT | against the best DeFT variant: THR | LAT | share of the main row\'s gain: THR | LAT |',
         '|---|---|---|---|---|---|---|---|---|---|---|']
    for z in SIZES:
        es = [e for e in ents if e['size'] == z]
        for p in RP26.PATTERNS:
            base = {n: D.group(MAIN, 'DeFT_P', es, n, [p])[0] for n in ('THR', 'LAT')}
            for r in rows + [MAIN]:
                L.append('| %s | %s | `%s` | %s | %s | %s | %s | %s | %s | %s | %s |' % (
                    z, p, r, eff(D.group(r, MAIN, es, 'THR', [p])) if r != MAIN else '', eff(D.group(r, MAIN, es, 'LAT', [p])) if r != MAIN else '',
                    eff(D.group(r, 'DeFT_P', es, 'THR', [p])), eff(D.group(r, 'DeFT_P', es, 'LAT', [p])),
                    eff(D.group(r, 'best', es, 'THR', [p])), eff(D.group(r, 'best', es, 'LAT', [p])),
                    share(D.group(r, 'DeFT_P', es, 'THR', [p])[0], base['THR']) if r != MAIN else '', share(D.group(r, 'DeFT_P', es, 'LAT', [p])[0], base['LAT']) if r != MAIN else ''))
    L += ['', '## Y.2 Without faults, the same two traffic patterns separately (Part C; ten seeds, THR over nine loads, interval over the seeds)', '',
          '| size | traffic | row | against the main row: THR | LAT | against DeFT_P: THR | LAT | share of the main row\'s gain: THR | LAT |', '|---|---|---|---|---|---|---|---|---|']
    for z in SIZES:
        for p in RP26.PATTERNS:
            base = {n: EC.group(MAIN, 'DeFT_P', z, n, [p])[0] for n in ('THR', 'LAT')}
            for r in rows + [MAIN]:
                L.append('| %s | %s | `%s` | %s | %s | %s | %s | %s | %s |' % (
                    z, p, r, eff(EC.group(r, MAIN, z, 'THR', [p])) if r != MAIN else '', eff(EC.group(r, MAIN, z, 'LAT', [p])) if r != MAIN else '',
                    eff(EC.group(r, 'DeFT_P', z, 'THR', [p])), eff(EC.group(r, 'DeFT_P', z, 'LAT', [p])),
                    share(EC.group(r, 'DeFT_P', z, 'THR', [p])[0], base['THR']) if r != MAIN else '', share(EC.group(r, 'DeFT_P', z, 'LAT', [p])[0], base['LAT']) if r != MAIN else ''))

    def cnt(row, z, p, f, i=1):
        """Mean over the masks of a size and the two seeds of f(run at load index i of the mask's ladder); None if the row has no such counter."""
        v = []
        for e in ents:
            if e['size'] != z:
                continue
            for s in RP26.SEEDS:
                x = R.get((row, z, p, e['mask'], lad(e, p)[i], s))
                y = f(x) if x is not None else None
                if y is not None:
                    v.append(y)
        return RP.mean(v) if v else None

    def fm(x, form):
        return form % x if x is not None else 'n/a'
    hops = lambda x: (x['hops_chip'] + x['hops_ipos']) / x['received'] if x.get('hops_chip') is not None and x.get('received') else None  # noqa: E731
    notdef = lambda x: 100.0 * x['entry_up_not_default'] / x['entry_up_moves'] if x.get('entry_up_moves') else None  # noqa: E731
    toup = lambda x: x['entry_up_age_mean'] - x['entry_inj_wait_mean'] if x.get('entry_up_age_mean') is not None and x.get('entry_inj_wait_mean') is not None else None  # noqa: E731
    acc = lambda x: x['accepted'] / x['offered'] if x.get('offered') else None  # noqa: E731
    L += ['', '## Y.3 Counters under faults at 1.0 x Lsat of DeFT-P on the mask (mean over the 16 masks and the two seeds)', '',
          '*imbalance*: the busiest VL (packets Down plus Up) over the mean VL. *hops*: head-flit forwards per received packet (rows of DEFT_LB only; for the rows of',
          'round 26 over all received packets of the run). *not DeFT-P\'s VL*, *to the Up move*: the counters of `entry_stats`, which the runs of round 26 do not have.', '',
          '| size | traffic | row | delivered | imbalance | hops per packet | not DeFT-P\'s VL (%) | from the injection to the Up move (cycles) |', '|---|---|---|---|---|---|---|---|']
    for z in SIZES:
        for p in RP26.PATTERNS:
            for r in ['DeFT_P', 'DeFT_B', MAIN] + rows:
                L.append('| %s | %s | `%s` | %s | %s | %s | %s | %s |' % (z, p, r, fm(cnt(r, z, p, acc), '%.3f'), fm(cnt(r, z, p, lambda x: x.get('vl_imbalance')), '%.2f'),
                                                                 fm(cnt(r, z, p, hops), '%.2f'), fm(cnt(r, z, p, notdef), '%.0f'), fm(cnt(r, z, p, toup), '%.0f')))
    L += ['', '## Y.4 Masks (of 16 per size) in which the row is ahead: of the main row, of DeFT_P, of the best DeFT variant', '',
          'Ahead = the mean over the two traffic patterns and the two seeds of the log ratio is on the good side (THR higher, LAT at 1.0 x Lsat lower).', '',
          '| size | row | ahead of the main row: THR | LAT | ahead of DeFT_P: THR | LAT | ahead of the best DeFT variant: THR | LAT |', '|---|---|---|---|---|---|---|---|']
    for z in SIZES:
        es = [e for e in ents if e['size'] == z]
        for r in rows + [MAIN]:
            c = []
            for ref in (MAIN, 'DeFT_P', 'best'):
                for n in ('THR', 'LAT'):
                    if r == ref:
                        c.append('')
                        continue
                    vs = [D.vm(r, ref, e, n) for e in es]
                    c.append('%d' % sum(1 for v in vs if v is not None and not D.wrong(v, n) and v != 0))
            L.append('| %s | `%s` | %s |' % (z, r, ' | '.join(c)))
    L.append('')
    RP.wmd('extra_E.md', L)
    print(RP.NL.join(L))


if __name__ == '__main__':
    main()
    extra_e()
