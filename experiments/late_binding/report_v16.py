"""v16 (Part H) report: equivalence of fixed-point Q tables with the float reference.

Inputs: results_v16_qbits/eval_runs.csv (make_eval_csv.py results_v16_qbits eval), results_v9/eval_runs.csv (float
reference), results_v16_qbits/qformat.json, ql_stats.csv (updates changed, residual range per run).
Outputs (results_v16_qbits/report/): equivalence.csv, summary.md, cost_table_qbits.md
"""
import csv
import json
import math
import os

from primary_from_csv import ci  # noqa: E402
from report_v4 import Data, load_csv  # noqa: E402
import report_v5 as R5  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
R16 = os.path.join(HERE, 'results_v16_qbits')
SIZES = ['2x2', '3x3', '4x4']
VARIANTS = ['CI_qlLA_G', 'FULL_qlLA_G']
BITS = [16, 12, 8]
SEEDS = range(41, 46)
MARGIN = {'LAT': 3.0, 'P99': 5.0, 'THR': 1.0}
FAULTY = {'2x2': '0x1111', '3x3': '0x111111111', '4x4': '0x1111111111111111'}


def scen(z):
    f = '0x0000' if z == '2x2' else '0x0'
    return [(f'{z}-uniform', f), (f'{z}-hotspot', f), (f'{z}-chipperm', f), (f'{z}-movinghot', f),
            (f'{z}-uniform', FAULTY[z])]


def main():
    out = os.path.join(R16, 'report')
    os.makedirs(out, exist_ok=True)
    R = {k: v for k, v in load_csv(os.path.join(HERE, 'results_v9', 'eval_runs.csv')).items()
         if k[0] in VARIANTS and k[4] in SEEDS}
    new = load_csv(os.path.join(R16, 'eval_runs.csv'))
    R.update(new)
    fmt = json.load(open(os.path.join(R16, 'qformat.json')))
    rows = []
    for z in SIZES:
        D = Data(R, scen(z), R5.ladder, SEEDS)
        for v in VARIANTS:
            for b in BITS:
                rec = dict(size=z, variant=v, bits=b, frac_bits=fmt[z]['frac_bits'][str(b)])
                eq = True
                for n in ('LAT', 'P99', 'THR'):
                    xs = D.per_seed(f'{v}-b{b}', v, n)
                    mu, h = ci(xs)
                    e, lo, hi = (100 * (math.exp(mu) - 1), 100 * (math.exp(mu - h) - 1), 100 * (math.exp(mu + h) - 1))
                    rec.update({f'{n}_effect': round(e, 2), f'{n}_lo': round(lo, 2), f'{n}_hi': round(hi, 2),
                                f'{n}_n': len(xs)})
                    eq &= -MARGIN[n] <= lo and hi <= MARGIN[n]
                rec['equivalent'] = eq
                rows.append(rec)
    with open(os.path.join(out, 'equivalence.csv'), 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator='\n')
        w.writeheader()
        w.writerows(rows)
    smallest = None
    for b in sorted(BITS):
        if all(r['equivalent'] for r in rows if r['bits'] == b):
            smallest = b
            break
    qs = list(csv.DictReader(open(os.path.join(R16, 'ql_stats.csv')))) if os.path.exists(
        os.path.join(R16, 'ql_stats.csv')) else []
    L = ['# v16 Q-table width: equivalence with the float reference (generated by report_v16.py)', '',
         f'New runs: {len(new)}. Reference: v9 float runs, seeds 41-45. Effect = mean over the 5 scenarios of the per-seed '
         'log ratio (fixed point / float), % with 95 % CI over the seeds. Margins: LAT +-3 %, P99 +-5 %, THR +-1 %.', '',
         '| size | variant | B (F) | LAT | P99 | THR | equivalent |', '|---|---|---|---|---|---|---|']
    for r in rows:
        cells = [f'{r[n + "_effect"]:+.2f} [{r[n + "_lo"]:+.2f}, {r[n + "_hi"]:+.2f}]' for n in ('LAT', 'P99', 'THR')]
        L.append(f'| {r["size"]} | {r["variant"]} | {r["bits"]} ({r["frac_bits"]}) | ' + ' | '.join(cells) +
                 f' | **{"yes" if r["equivalent"] else "no"}** |')
    L += ['', f'**Smallest B equivalent for both variants on every size: {smallest if smallest else "none of 16, 12, 8"}.**', '']
    if qs:
        L += ['## Learning activity (share of updates that changed the stored residual; residual range)', '',
              '| size | variant | B | updates changed (mean over runs) | R min | R max |', '|---|---|---|---|---|---|']
        for z in SIZES:
            for v in VARIANTS:
                for b in BITS:
                    xs = [r for r in qs if (r['size'], r['variant'], r['bits']) == (z, v, str(b))]
                    if not xs:
                        continue
                    ch = sum(float(r['changed_share']) for r in xs) / len(xs)
                    L.append(f'| {z} | {v} | {b} | {100 * ch:.1f} % | {min(float(r["r_min"]) for r in xs):.3g} | '
                             f'{max(float(r["r_max"]) for r in xs):.3g} |')
        L.append('')
    open(os.path.join(out, 'summary.md'), 'w', newline='\n').write('\n'.join(L) + '\n')
    # updated cost row for the Q table
    C = {'2x2': 4, '3x3': 9, '4x4': 16}
    width = smallest if smallest else 16
    T = ['# Q-table cost with the tested entry width (v16; update of results_v12_energy/report/cost_table.md)', '',
         f'Entry width B = {width} bits ({"smallest width equivalent everywhere" if smallest else "no tested width was equivalent everywhere; 16 bits kept"}). '
         'Q table per router with an adaptive choice: C destination-chiplet keys x 5 outputs x B bits. A router\'s input '
         'buffers: 1536 bits (6 ports x 2 VCs x 4 flits x 32 bits).', '',
         '| size | Q table (bits) | share of the input-buffer bits | at 16 bits |', '|---|---|---|---|']
    for z, c in C.items():
        bits = c * 5 * width
        T.append(f'| {z} | {bits} | {100 * bits / 1536:.0f} % | {c * 5 * 16} ({100 * c * 80 / 1536:.0f} %) |')
    open(os.path.join(out, 'cost_table_qbits.md'), 'w', newline='\n').write('\n'.join(T) + '\n')
    print('\n'.join(L))
    print('\n'.join(T))


if __name__ == '__main__':
    main()
