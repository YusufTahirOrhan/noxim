"""Analysis of the v3 confirmatory runs, following results_v3/PREREGISTRATION.md.

Inputs (CSV only): results_v3/confirm_runs.csv and results_v3/window_runs.csv (from
make_eval_csv.py), results_v2/eval_runs.csv (v2 estimates, seeds 1-10, for comparison only),
results_v2/load_points.json.
Outputs: results_v3/primary_v3.csv, results_v3/confirm_summary.md, results_v3/confirm_primary.png
Usage: python3 report_v3.py
"""
import csv
import json
import math
import os

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt  # noqa: E402

from primary_from_csv import SCEN, ci, holm, ttest  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
R3 = os.path.join(HERE, 'results_v3')
LP = json.load(open(os.path.join(HERE, 'results_v2', 'load_points.json')))
LOADS = {'0.8': 2, '1.0': 3, '1.2': 4}
SEEDS = list(range(11, 21))
WSEEDS = list(range(11, 16))
WSCEN = [('uniform', '0x0000'), ('hotspot', '0x0000'), ('movinghot', '0x0000')]
PRIMARY = [('CI_heur', 'DeFT_tm'), ('CI_heurLA', 'DeFT_tm'), ('CI_qlLA', 'DeFT_tm'), ('CI_qlLA', 'CI_heurLA'),
           ('FULL_heurLA', 'DeFT_tm')]
SECONDARY = [('CI_ql', 'DeFT_tm'), ('FULL_qlLA', 'DeFT_tm'), ('CI_ql', 'CI_heur'), ('FULL_qlLA', 'FULL_heurLA')]
VARIANTS = ['DeFT_tm', 'CI_heur', 'CI_heurLA', 'CI_ql', 'CI_qlLA', 'FULL_heurLA', 'FULL_qlLA']
METRIC = {'LAT': 'latency', 'P99': 'p99'}


def rate(p, m, load):
    return LP[f'{p}__{m}']['eval'][LOADS[load]]


def load_csv(path):
    out = {}
    for r in csv.DictReader(open(path)):
        out[(r['variant'], r['pattern'], r['mask'], float(r['rate']), int(r['seed']))] = \
            dict(latency=float(r['latency']), p99=float(r['p99']), accepted=float(r['accepted']),
                 dead_ends=int(r['dead_ends']))
    return out


def per_seed(R, a, b, metric, load, seeds, scen=SCEN):
    out = []
    for s in seeds:
        try:
            out.append(sum(math.log(R[(a, p, m, rate(p, m, load), s)][METRIC[metric]] /
                                    R[(b, p, m, rate(p, m, load), s)][METRIC[metric]]) for p, m in scen) / len(scen))
        except KeyError:
            pass
    return out


def pct(xs):
    mu, h = ci(xs)
    return 100 * (math.exp(mu) - 1), 100 * (math.exp(mu - h) - 1), 100 * (math.exp(mu + h) - 1)


def main():
    R = load_csv(os.path.join(R3, 'confirm_runs.csv'))
    W = load_csv(os.path.join(R3, 'window_runs.csv'))
    V2 = load_csv(os.path.join(HERE, 'results_v2', 'eval_runs.csv'))
    expected = len(VARIANTS) * len(SCEN) * 3 * len(SEEDS)
    missing = [(v, p, m, ld, s) for v in VARIANTS for p, m in SCEN for ld in LOADS for s in SEEDS
               if (v, p, m, rate(p, m, ld), s) not in R]
    dead = sum(x['dead_ends'] for x in R.values()) + sum(x['dead_ends'] for x in W.values())

    # ---- primary ----
    prim = []
    for a, b in PRIMARY:
        for met in ('LAT', 'P99'):
            xs = per_seed(R, a, b, met, '1.0', SEEDS)
            e, lo, hi = pct(xs)
            v2e, v2lo, v2hi = pct(per_seed(V2, a, b, met, '1.0', range(1, 11)))
            prim.append(dict(variant=a, reference=b, metric=met, n_seeds=len(xs), effect_pct=round(e, 2),
                             ci_low=round(lo, 2), ci_high=round(hi, 2), p=ttest(xs),
                             v2_effect_pct=round(v2e, 2), v2_ci_low=round(v2lo, 2), v2_ci_high=round(v2hi, 2)))
    for x, q in zip(prim, holm([x['p'] for x in prim])):
        x['p_holm'] = q
        if q < 0.05 and x['effect_pct'] < 0:
            x['verdict'] = 'confirmed'
        elif q < 0.05:
            x['verdict'] = 'contradicted'
        else:
            x['verdict'] = 'not confirmed'
    with open(os.path.join(R3, 'primary_v3.csv'), 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(prim[0]), lineterminator='\n')
        w.writeheader()
        for x in prim:
            w.writerow({k: (f'{v:.4g}' if k in ('p', 'p_holm') else v) for k, v in x.items()})

    L = ['# v3 confirmatory analysis (seeds 11-20; generated by report_v3.py)', '',
         f'Runs: {len(R)} of {expected} confirmatory, {len(W)} of 45 window runs; missing: {len(missing)}; '
         f'dead-end events: {dead}.', '',
         '## Primary results (pre-registered; Holm over 10 tests; confirmation = Holm p < 0.05 with the v2 sign)', '',
         'Effect: mean over the 11 scenarios of the per-seed log ratio at 1.0 x Lsat, as % change (lower is better).', '',
         '| variant | reference | metric | v3 effect % [95 % CI] | p | p (Holm) | verdict | v2 effect (seeds 1-10) |',
         '|---|---|---|---|---|---|---|---|']
    for x in prim:
        L.append(f'| {x["variant"]} | {x["reference"]} | {x["metric"]} | {x["effect_pct"]:+.2f} '
                 f'[{x["ci_low"]:+.2f}, {x["ci_high"]:+.2f}] | {x["p"]:.3g} | {x["p_holm"]:.3g} | **{x["verdict"]}** | '
                 f'{x["v2_effect_pct"]:+.2f} [{x["v2_ci_low"]:+.2f}, {x["v2_ci_high"]:+.2f}] |')
    L.append('')

    # ---- secondary: other loads, other comparisons ----
    L += ['## Secondary: all comparisons at 0.8, 1.0 and 1.2 x Lsat (unadjusted 95 % CI; descriptive)', '',
          '| variant | reference | LAT 0.8 | LAT 1.0 | LAT 1.2 | P99 0.8 | P99 1.0 | P99 1.2 |',
          '|---|---|---|---|---|---|---|---|']
    for a, b in PRIMARY + SECONDARY:
        cells = []
        for met in ('LAT', 'P99'):
            for ld in LOADS:
                e, lo, hi = pct(per_seed(R, a, b, met, ld, SEEDS))
                cells.append(f'{e:+.1f} [{lo:+.1f}, {hi:+.1f}]')
        L.append(f'| {a} | {b} | ' + ' | '.join(cells) + ' |')
    L.append('')

    # accepted throughput, max over the three loads (heavily capped)
    def thr(v, p, m, s):
        acc = [(R[(v, p, m, rate(p, m, ld), s)]['accepted'], ld) for ld in LOADS]
        best, at = max(acc)
        return best, at == '1.2' and best >= 0.95 * 8 * rate(p, m, '1.2')
    L += ['## Secondary: accepted throughput, max over the 0.8/1.0/1.2 x Lsat loads (NOT the v2 saturation '
          'throughput; capped cells counted)', '',
          '| variant | reference | effect % [95 % CI] | capped seed-scenario cells (variant or reference) |',
          '|---|---|---|---|']
    for a, b in PRIMARY + SECONDARY:
        xs = [sum(math.log(thr(a, p, m, s)[0] / thr(b, p, m, s)[0]) for p, m in SCEN) / len(SCEN) for s in SEEDS]
        e, lo, hi = pct(xs)
        capped = sum(1 for p, m in SCEN for s in SEEDS if thr(a, p, m, s)[1] or thr(b, p, m, s)[1])
        L.append(f'| {a} | {b} | {e:+.2f} [{lo:+.2f}, {hi:+.2f}] | {capped} of {len(SCEN) * len(SEEDS)} |')
    L.append('')

    # per-scenario at 1.0 x Lsat
    for met in ('LAT', 'P99'):
        L += [f'## Secondary: per-scenario {met} at 1.0 x Lsat, % change (unadjusted 95 % CI; `°` = CI excludes 0)', '',
              '| variant vs ref | ' + ' | '.join(f'{p} {m}' for p, m in SCEN) + ' |', '|---|' + '---|' * len(SCEN)]
        for a, b in PRIMARY + SECONDARY:
            cells = []
            for p, m in SCEN:
                e, lo, hi = pct(per_seed(R, a, b, met, '1.0', SEEDS, [(p, m)]))
                cells.append(f'{e:+.1f}{"°" if hi < 0 or lo > 0 else ""}')
            L.append(f'| {a} vs {b} | ' + ' | '.join(cells) + ' |')
        L.append('')

    # ---- window sensitivity ----
    L += ['## Secondary: window sensitivity (1.0 x Lsat, seeds 11-15; 8000 vs 40000 measured cycles)', '',
          'Pre-stated reading: "possible short-window artefact" if at 40000 cycles the sign flips, or the interval '
          'includes 0 while the 8000-cycle interval excludes it; otherwise "consistent across windows".', '',
          '| scenario | variant vs DeFT_tm | metric | 8000 cycles % [95 % CI] | 40000 cycles % [95 % CI] | reading |',
          '|---|---|---|---|---|---|']
    wrows = []
    for p, m in WSCEN:
        for a in ('CI_heurLA', 'CI_qlLA'):
            for met in ('LAT', 'P99'):
                s8 = pct(per_seed(R, a, 'DeFT_tm', met, '1.0', WSEEDS, [(p, m)]))
                s40 = pct(per_seed(W, a, 'DeFT_tm', met, '1.0', WSEEDS, [(p, m)]))
                excl8 = s8[2] < 0 or s8[1] > 0
                excl40 = s40[2] < 0 or s40[1] > 0
                flip = (s8[0] < 0) != (s40[0] < 0)
                reading = 'possible short-window artefact' if (flip or (excl8 and not excl40)) else 'consistent across windows'
                wrows.append(reading)
                L.append(f'| {p} {m} | {a} | {met} | {s8[0]:+.1f} [{s8[1]:+.1f}, {s8[2]:+.1f}] | '
                         f'{s40[0]:+.1f} [{s40[1]:+.1f}, {s40[2]:+.1f}] | {reading} |')
    L.append('')
    L.append('Absolute mean latency (cycles), mean over seeds 11-15:')
    L.append('')
    L.append('| scenario | variant | 8000 cycles | 40000 cycles |')
    L.append('|---|---|---|---|')
    for p, m in WSCEN:
        for v in ('DeFT_tm', 'CI_heurLA', 'CI_qlLA'):
            a8 = [R[(v, p, m, rate(p, m, '1.0'), s)]['latency'] for s in WSEEDS]
            a40 = [W[(v, p, m, rate(p, m, '1.0'), s)]['latency'] for s in WSEEDS]
            L.append(f'| {p} {m} | {v} | {sum(a8) / len(a8):.1f} | {sum(a40) / len(a40):.1f} |')
    L.append('')
    if missing:
        L += ['## Missing runs'] + [f'- {x}' for x in missing]
    open(os.path.join(R3, 'confirm_summary.md'), 'w', newline='\n').write('\n'.join(L) + '\n')

    # ---- figure: v2 (hypothesis-generating) vs v3 (confirmatory) primary effects ----
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.2), sharey=True)
    labels = [f'{a} vs {b}' for a, b in PRIMARY]
    for ax, met in zip(axes, ('LAT', 'P99')):
        xs = [x for x in prim if x['metric'] == met]
        for i, x in enumerate(xs):
            y = len(xs) - 1 - i
            ax.errorbar([x['v2_effect_pct']], [y + 0.15], xerr=[[x['v2_effect_pct'] - x['v2_ci_low']],
                        [x['v2_ci_high'] - x['v2_effect_pct']]], fmt='o', mfc='white', color='#8a8984', capsize=3, ms=6,
                        label='v2, seeds 1-10 (secondary, hypothesis-generating)' if i == 0 else None)
            col = {'confirmed': '#2a78d6', 'contradicted': '#eb6834', 'not confirmed': '#52514e'}[x['verdict']]
            ax.errorbar([x['effect_pct']], [y - 0.15], xerr=[[x['effect_pct'] - x['ci_low']], [x['ci_high'] - x['effect_pct']]],
                        fmt='o', color=col, capsize=3, ms=6, label='v3, seeds 11-20 (confirmatory)' if i == 0 else None)
        ax.axvline(0, color='#52514e', lw=0.8)
        ax.set_yticks(range(len(labels)))
        ax.set_yticklabels(labels[::-1], fontsize=8)
        ax.set_xlabel('% change at 1.0 x Lsat, mean over 11 scenarios (lower is better)')
        ax.set_title({'LAT': 'Mean latency', 'P99': 'p99 latency'}[met], fontsize=10)
        ax.grid(True, axis='x', color='#e6e5e1', lw=0.6)
        for sp in ('top', 'right'):
            ax.spines[sp].set_visible(False)
    h, lab = axes[0].get_legend_handles_labels()
    fig.legend(h, lab, fontsize=8, frameon=False, loc='lower center', ncol=2)
    fig.suptitle('Near-saturation latency: v2 estimate vs v3 confirmation (95 % CI over seeds; filled blue = '
                 'confirmed, Holm over 10 tests)', fontsize=9)
    fig.tight_layout(rect=(0, 0.07, 1, 1))
    fig.savefig(os.path.join(R3, 'confirm_primary.png'), dpi=130)
    plt.close(fig)
    print(f'runs {len(R)}/{expected}, window {len(W)}/45, missing {len(missing)}, dead {dead}')
    for x in prim:
        print(x['variant'], x['reference'], x['metric'], x['effect_pct'], x['ci_low'], x['ci_high'],
              f'{x["p_holm"]:.3g}', x['verdict'])
    print('window readings:', {r: wrows.count(r) for r in set(wrows)})


if __name__ == '__main__':
    main()
