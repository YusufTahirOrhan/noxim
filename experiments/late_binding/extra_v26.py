#!/usr/bin/env python3
"""v26: descriptive tables for FINDINGS.md that the pre-registered report does not have (report/extra_B.md).

Everything here is descriptive: unadjusted, never called significant. The descriptors of a mask were fixed before any evaluation run existed
(results_v26_faults/DECISIONS.md, "Report"):
  share      faulty VLs / all VLs (the rate)
  one        chiplets with one functional VL (a packet to such a chiplet has no entry to choose)
  maxf       the largest number of faults in one chiplet
  hot_one    of the three chiplets that hold a hotspot router (chiplets 0, 1 and CX, gen_traffic.py), those with one functional VL
  lsat_rel   Lsat of DeFT_P on the mask / Lsat of DeFT_P fault-free (round 25, the same rule): what is left of the capacity

usage: python3 extra_v26.py      (V26_RES overrides the results directory)
"""
import json
import os

import scipy.stats as st

import report_v26 as RP

RES, OUT, HERE = RP.RES, RP.OUT, RP.HERE
MAIN, SECOND, REFS, RATES, PATTERNS = RP.MAIN, RP.SECOND, RP.REFS, RP.RATES, RP.PATTERNS
NL = chr(10)
CX = {'2x2': 2, '3x3': 3, '4x4': 4}
FREE = {'2x2': '0x0000', '3x3': '0x0', '4x4': '0x0'}


def spearman(xs, ys):
    """'rho (n)' of the pairs with both values; '-' if one of the two does not vary."""
    v = [(x, y) for x, y in zip(xs, ys) if x is not None and y is not None]
    if len(v) < 4 or len({x for x, _ in v}) < 2 or len({y for _, y in v}) < 2:
        return '-'
    return '%+.2f' % st.spearmanr([x for x, _ in v], [y for _, y in v])[0]


def main():
    P = json.load(open(os.path.join(RES, 'load_points_v26.json')))
    E = json.load(open(os.path.join(RES, 'masks_v26.json')))['part_b']
    f = os.path.join(RES, 'drops.json')
    drops = json.load(open(f))['dropped'] if os.path.exists(f) else []
    E = [e for e in E if not ('rate8_4x4' in drops and e['size'] == '4x4' and e['rate'] == '8/16') and not ('masks13_16' in drops and e['index'] >= 13)]
    R = RP.load_runs(os.path.join(RES, 'fault_rate_runs.csv'))
    D = RP.Data(R, lambda e, p: P['%s__%s__%s' % (e['size'], p, e['mask'])]['eval'], E, PATTERNS, RP.SEEDS, REFS)
    FF = json.load(open(os.path.join(HERE, 'results_v25_confirm', 'load_points_v25.json')))
    sizes = [z for z in RP.SIZES if any(e['size'] == z for e in E)]

    def lsat(e, p):
        return P['%s__%s__%s' % (e['size'], p, e['mask'])]['lsat']

    def lrel(e, p):
        return lsat(e, p) / FF['%s__%s__%s__p2' % (e['size'], p, FREE[e['size']])]['lsat']

    def hot(e):
        return [0, 1, CX[e['size']]]

    for e in E:
        e['share'] = e['n_faulty'] / (4.0 * len(e['faults_per_chiplet']))
        e['hot_one'] = sum(1 for c in hot(e) if e['faults_per_chiplet'][c] == 3)
        e['hot_faults'] = sum(e['faults_per_chiplet'][c] for c in hot(e))
        e['lsat_rel'] = RP.mean(lrel(e, p) for p in PATTERNS)

    def cellm(z, rate):
        return [e for e in E if e['size'] == z and e['rate'] == rate]
    cells = [(z, rate) for z in sizes for rate in RATES if cellm(z, rate)]
    COMP = (('best', 'THR'), ('best', 'LAT'), ('DeFT_P', 'THR'), ('DeFT_P', 'LAT'))
    CN = {'best': 'the best reference', 'DeFT_P': 'DeFT_P'}

    L = ['# v26 Part B: descriptive tables beyond the pre-registered report (generated by extra_v26.py)', '',
         'Unadjusted and descriptive; nothing here is a test. Effects are those of `summary_B.md` (unit = mask, effect [95 % CI] over the masks of the group). Descriptors of a',
         'mask, fixed before the evaluation runs: the share of faulty VLs; the number of chiplets with one functional VL (a packet to such a chiplet has no entry to choose);',
         'the largest number of faults in one chiplet; of the three chiplets that hold a hotspot router (0, 1 and CX), those with one functional VL; Lsat of DeFT_P on the mask',
         'relative to its fault-free Lsat (round 25, the same rule).', '']

    # ---- X.1 rank correlations ----
    L += ['## X.1 Rank correlation (Spearman) of the per-mask effect of `CI_heurLA_X_LF` with the descriptors, over the masks of a size', '',
          'The per-mask value is V_m (both traffic patterns). For THR a positive correlation means: the more of the descriptor, the larger the gain. For LAT the effect is negative',
          'when the row is better, so a positive correlation means: the more of the descriptor, the smaller the gain.', '',
          '| size | masks | against | metric | share of faulty VLs | chiplets with one functional VL | largest number of faults in a chiplet | Lsat relative to fault-free |', '|---|---|---|---|---|---|---|---|']
    for z in sizes:
        es = [e for e in E if e['size'] == z]
        for ref, n in COMP:
            v = [D.vm(MAIN, ref, e, n) for e in es]
            L.append('| %s | %d | %s | %s | %s |' % (z, len(es), CN[ref], n, ' | '.join(spearman([e[k] for e in es], v) for k in ('share', 'chiplets_with_one_functional_vl', 'max_faults_in_a_chiplet', 'lsat_rel'))))
    L.append('')

    # ---- X.2 the trend per traffic pattern ----
    L += ['## X.2 Rank correlation of the per-mask effect with the share of faulty VLs, per traffic pattern (against the best reference)', '',
          '| size | traffic | THR | LAT | P99 |', '|---|---|---|---|---|']
    for z in sizes:
        es = [e for e in E if e['size'] == z]
        for t in PATTERNS:
            L.append('| %s | %s | %s |' % (z, t, ' | '.join(spearman([e['share'] for e in es], [D.vm(MAIN, 'best', e, n, [t]) for e in es]) for n in RP.METRICS)))
    L.append('')

    # ---- X.3 within a rate, by the number of chiplets with one functional VL ----
    L += ['## X.3 Within one rate: the effect of `CI_heurLA_X_LF` by the number of chiplets with one functional VL', '',
          '| size | rate | chiplets with one functional VL | masks | THR against the best reference | LAT against the best reference | THR against DeFT_P | LAT against DeFT_P |',
          '|---|---|---|---|---|---|---|---|']
    for z, rate in cells:
        es = cellm(z, rate)
        vals = sorted({e['chiplets_with_one_functional_vl'] for e in es})
        if len(vals) < 2:
            continue
        for v in vals:
            g = [e for e in es if e['chiplets_with_one_functional_vl'] == v]
            L.append('| %s | %s | %d | %d | %s |' % (z, rate, v, len(g), ' | '.join(RP.eff(D.group(MAIN, ref, g, n)) for ref, n in COMP)))
    L += ['', 'Cells in which every mask has the same number are left out (the low rates: no chiplet can lose three VLs).', '']

    # ---- X.4 hotspot traffic by the hot chiplets ----
    L += ['## X.4 Hotspot traffic: the effect of `CI_heurLA_X_LF` by the number of hot chiplets (0, 1 and CX) with one functional VL (all rates of the size)', '',
          '| size | hot chiplets with one functional VL | masks | rates in the group | THR against the best reference | LAT against the best reference | THR against DeFT_P | LAT against DeFT_P |',
          '|---|---|---|---|---|---|---|---|']
    for z in sizes:
        es = [e for e in E if e['size'] == z]
        for v in sorted({e['hot_one'] for e in es}):
            g = [e for e in es if e['hot_one'] == v]
            L.append('| %s | %d | %d | %s | %s |' % (z, v, len(g), ', '.join(r for r in RATES if any(e['rate'] == r for e in g)),
                                                    ' | '.join(RP.eff(D.group(MAIN, ref, g, n, ['hotspot'])) for ref, n in COMP)))
    L.append('')

    # ---- X.5 cells behind against cells ahead ----
    L += ['## X.5 The (mask, traffic) cells in which `CI_heurLA_X_LF` is behind, next to those in which it is ahead (mean over the two seeds; means of the descriptors over the cells)', '',
          '| size | against | metric | side | cells | of them hotspot | mean share of faulty VLs | mean share of chiplets with one functional VL | mean Lsat relative to fault-free | '
          'mean effect | the reference is DeFT_P / DeFT_B / DeFT_Dis / DeFT_Ran |', '|---|---|---|---|---|---|---|---|---|---|---|']
    for z in sizes:
        es = [e for e in E if e['size'] == z]
        for ref, n in COMP:
            allc = [(D.cell(MAIN, ref, e, p, n), e, p) for e in es for p in PATTERNS]
            allc = [x for x in allc if x[0] is not None]
            for side, g in (('behind', [x for x in allc if D.wrong(x[0], n)]), ('ahead or level', [x for x in allc if not D.wrong(x[0], n)])):
                if not g:
                    L.append('| %s | %s | %s | %s | 0 | | | | | | |' % (z, CN[ref], n, side))
                    continue
                who = [D.best(e, p, n) if ref == 'best' else ref for _, e, p in g]
                L.append('| %s | %s | %s | %s | %d | %d | %.3f | %.3f | %.2f | %+.1f %% | %s |' % (
                    z, CN[ref], n, side, len(g), sum(1 for _, _, p in g if p == 'hotspot'), RP.mean(e['share'] for _, e, _ in g),
                    RP.mean(e['chiplets_with_one_functional_vl'] / float(len(e['faults_per_chiplet'])) for _, e, _ in g), RP.mean(lrel(e, p) for _, e, p in g),
                    RP.pct(RP.mean(v for v, _, _ in g)), ' / '.join(str(sum(1 for w in who if w == r)) for r in REFS)))
    L.append('')

    # ---- X.6 counts per reference row ----
    def side(t, n):
        """'+' hypothesised side with the interval excluding 0, '(+)' hypothesised side, '(-)' other side, '-' other side with the interval excluding 0."""
        m, lo, hi, p, k = t
        good = (m > 0) == RP.HIGHER[n]
        clear = not RP.isnan(lo) and (lo > 0 or hi < 0)
        return ('+' if clear else '(+)') if good else ('-' if clear else '(-)')
    L += ['## X.6 Per reference row: in how many of the %d (size, rate) cells the row is ahead (unadjusted 95 %% interval of the cell excluding 0 / not excluding 0) and behind' % len(cells), '',
          'Counts as "ahead, interval excludes 0 / ahead / behind / behind, interval excludes 0".', '',
          '| row | metric | DeFT_P | DeFT_B | DeFT_Dis | DeFT_Ran | best reference |', '|---|---|---|---|---|---|---|']
    for row in (MAIN, SECOND):
        for n in RP.METRICS:
            c = []
            for ref in REFS + ['best']:
                s = [side(D.group(row, ref, cellm(z, rate), n), n) for z, rate in cells]
                c.append(' / '.join(str(s.count(x)) for x in ('+', '(+)', '(-)', '-')))
            L.append('| %s | %s | %s |' % (row, n, ' | '.join(c)))
    L.append('')

    # ---- X.7 the second row against the main row ----
    L += ['## X.7 `CI_heurLA_O_LF` against `CI_heurLA_X_LF`: masks in which the second row is the better of the two (of the masks of the cell)', '',
          '| size | rate | masks | higher THR | lower LAT | lower P99 | THR against the best reference: second row | main row |', '|---|---|---|---|---|---|---|---|']
    for z, rate in cells:
        es = cellm(z, rate)
        c = []
        for n in RP.METRICS:
            v = [D.vm(SECOND, MAIN, e, n) for e in es]
            c.append(str(sum(1 for x in v if x is not None and x != 0 and not D.wrong(x, n))))
        L.append('| %s | %s | %d | %s | %s | %s |' % (z, rate, len(es), ' | '.join(c), RP.eff(D.group(SECOND, 'best', es, 'THR')), RP.eff(D.group(MAIN, 'best', es, 'THR'))))
    L.append('')

    # ---- X.8 identical cells ----
    L += ['## X.8 Runs in which `CI_heurLA_X_LF` and DeFT_P give the same accepted throughput and the same mean latency (same mask, traffic, load and seed)', '',
          'With one functional VL in every chiplet the two rows are the same mechanism (round 25, k = 3). A random mask leaves some chiplets a choice, so the runs differ unless',
          'no packet meets a choice.', '',
          '| size | rate | runs of the main row | identical to DeFT_P | masks in which every run is identical |', '|---|---|---|---|---|']
    for z, rate in cells:
        es = cellm(z, rate)
        tot = same = mall = 0
        for e in es:
            k = j = 0
            for p in PATTERNS:
                for r in D.lad(e, p):
                    for s in RP.SEEDS:
                        a, b = R.get((MAIN, z, p, e['mask'], r, s)), R.get(('DeFT_P', z, p, e['mask'], r, s))
                        if a is None or b is None:
                            continue
                        k += 1
                        j += a['accepted'] == b['accepted'] and a['latency'] == b['latency']
            tot += k
            same += j
            mall += k > 0 and j == k
        L.append('| %s | %s | %d | %d | %d |' % (z, rate, tot, same, mall))
    L.append('')
    os.makedirs(OUT, exist_ok=True)
    RP.wmd('extra_B.md', L)
    print(NL.join(L))


if __name__ == '__main__':
    main()
