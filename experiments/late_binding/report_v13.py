"""v13 (Part E) report: application traces, normalised to DeFT(rho*) (as DeFT's Fig. 6).

Input: results_v13_apps/app_runs.csv. Outputs (results_v13_apps/report/): summary.md, normalised.csv,
apps_{fault-free,0x1111}.{png,pdf}
"""
import csv
import math
import os

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
R13 = os.path.join(HERE, 'results_v13_apps')
METHODS = ['DeFT', 'MTR', 'RC', 'DeFT_Dis', 'DeFT_Ran', 'XY_SP', 'DeFT_OE_G', 'CI_heurLA_G', 'CI_qlLA_G', 'FULL_qlLA_G']
LABEL = {'DeFT': 'DeFT(rho*)', 'DeFT_Dis': 'DeFT-Dis', 'DeFT_Ran': 'DeFT-Ran', 'XY_SP': 'XY-SP'}
COL = {'DeFT': '#52514e', 'MTR': '#c0392b', 'RC': '#eb6834', 'DeFT_Dis': '#8e8d87', 'DeFT_Ran': '#b9b7af',
       'XY_SP': '#6b5b95', 'DeFT_OE_G': '#e0a800', 'CI_heurLA_G': '#4a3aa7', 'CI_qlLA_G': '#1baf7a',
       'FULL_qlLA_G': '#2a78d6'}
METRICS = [('latency', 'mean latency'), ('p99', 'p99 latency'), ('completion_cycles', 'cycles to complete the window')]


def geo(xs):
    return math.exp(sum(math.log(x) for x in xs) / len(xs)) if xs else float('nan')


def main():
    out = os.path.join(R13, 'report')
    os.makedirs(out, exist_ok=True)
    rows = list(csv.DictReader(open(os.path.join(R13, 'app_runs.csv'))))
    bad = [r for r in rows if r['finished'] != 'True' or r['injected'] != r['delivered']]
    rows = [r for r in rows if r not in bad]
    R = {(r['benchmark'], r['method'], r['mask'], int(r['seed'])): r for r in rows}
    bench = sorted({r['benchmark'] for r in rows})
    masks = sorted({r['mask'] for r in rows})
    seeds = sorted({int(r['seed']) for r in rows})
    norm = []
    for b in bench:
        for m in masks:
            for v in METHODS:
                vals = {}
                for key, _ in METRICS:
                    rs = [float(R[(b, v, m, s)][key]) / float(R[(b, 'DeFT', m, s)][key]) for s in seeds
                          if (b, v, m, s) in R and (b, 'DeFT', m, s) in R]
                    vals[key] = geo(rs)
                if not math.isnan(vals['latency']):
                    abs_lat = geo([float(R[(b, v, m, s)]['latency']) for s in seeds if (b, v, m, s) in R])
                    norm.append(dict(benchmark=b, mask=m, method=v, abs_latency=round(abs_lat, 2),
                                     **{f'norm_{k}': round(x, 4) for k, x in vals.items()}))
    with open(os.path.join(out, 'normalised.csv'), 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(norm[0]), lineterminator='\n')
        w.writeheader()
        w.writerows(norm)
    L = ['# v13 application traces: normalised to DeFT(rho*) (generated by report_v13.py)', '',
         f'Runs: {len(rows) + len(bad)}; not finished or not drained (excluded): {len(bad)}. Geometric mean over seeds '
         f'{", ".join(map(str, seeds))} of the per-seed ratio to DeFT(rho*) on the same benchmark, mask and seed.', '']
    for m in masks:
        ms = [v for v in METHODS if any(x['method'] == v and x['mask'] == m for x in norm)]
        for key, title in METRICS:
            L += [f'## {"fault-free" if int(m, 16) == 0 else "VL mask " + m}: {title} (DeFT(rho*) = 1)', '',
                  '| benchmark | ' + ' | '.join(LABEL.get(v, v) for v in ms) + ' |', '|---|' + '---|' * len(ms)]
            for b in bench:
                cells = []
                for v in ms:
                    x = next((y for y in norm if (y['benchmark'], y['mask'], y['method']) == (b, m, v)), None)
                    cells.append(f'{x["norm_" + key]:.3f}' if x else 'n/a')
                L.append(f'| {b.split("_")[0]} | ' + ' | '.join(cells) + ' |')
            gm = []
            for v in ms:
                xs = [y['norm_' + key] for y in norm if y['mask'] == m and y['method'] == v]
                gm.append(f'**{geo(xs):.3f}**')
            L += ['| geometric mean | ' + ' | '.join(gm) + ' |', '']
        L += [f'Absolute mean latency of DeFT(rho*) (cycles): ' +
              ', '.join(f'{b.split("_")[0]} {next(y["abs_latency"] for y in norm if (y["benchmark"], y["mask"], y["method"]) == (b, m, "DeFT")):.1f}'
                        for b in bench), '']
        for key, title in METRICS[:2]:
            fig, ax = plt.subplots(figsize=(15, 4.4))
            wbar = 0.8 / len(ms)
            for i, v in enumerate(ms):
                ys = [next((y['norm_' + key] for y in norm if (y['benchmark'], y['mask'], y['method']) == (b, m, v)),
                           float('nan')) for b in bench]
                ys.append(geo([y for y in ys if not math.isnan(y)]))
                ax.bar([j + (i - len(ms) / 2 + 0.5) * wbar for j in range(len(bench) + 1)], ys, wbar * 0.95,
                       color=COL[v], label=LABEL.get(v, v))
            ax.axhline(1.0, color='#52514e', lw=0.8)
            ax.set_xticks(range(len(bench) + 1))
            ax.set_xticklabels([b.split('_')[0] for b in bench] + ['geo. mean'])
            ax.set_ylabel(f'{title} / DeFT(rho*)')
            if any(y['norm_' + key] > 3 for y in norm if y['mask'] == m):
                ax.set_yscale('log')
            ax.set_title(f'PARSEC traces (Netrace), 2x2, {"fault-free" if int(m, 16) == 0 else "VL mask " + m}: '
                         f'{title} normalised to DeFT(rho*)', fontsize=10)
            ax.legend(frameon=False, fontsize=8, ncol=5)
            ax.grid(True, axis='y', color='#e6e5e1', lw=0.6)
            fig.tight_layout()
            tag = 'fault-free' if int(m, 16) == 0 else m
            for ext in ('png', 'pdf'):
                fig.savefig(os.path.join(out, f'apps_{key}_{tag}.{ext}'), dpi=125)
            plt.close(fig)
    if bad:
        L += ['## Excluded runs', ''] + [f'- {r["benchmark"]} {r["method"]} {r["mask"]} seed {r["seed"]}' for r in bad]
    open(os.path.join(out, 'summary.md'), 'w', newline='\n').write('\n'.join(L) + '\n')
    print('\n'.join(L[:60]))


if __name__ == '__main__':
    main()
