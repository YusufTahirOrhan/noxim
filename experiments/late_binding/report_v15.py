"""v15 (Part G) report: two applications at once, normalised to DeFT(rho*).

Input: results_v15_apps2/pair_runs.csv. Outputs (results_v15_apps2/report/): summary.md, normalised.csv,
pairs_{latency,p99,completion}_s{S}_{fault-free,0x1111}.{png,pdf}
"""
import csv
import math
import os

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
R15 = os.path.join(HERE, 'results_v15_apps2')
METHODS = ['DeFT', 'MTR', 'RC', 'DeFT_Dis', 'DeFT_Ran', 'XY_SP', 'DeFT_OE_G', 'CI_heurLA_G', 'CI_qlLA_G', 'FULL_qlLA_G']
LABEL = {'DeFT': 'DeFT(rho*)', 'DeFT_Dis': 'DeFT-Dis', 'DeFT_Ran': 'DeFT-Ran', 'XY_SP': 'XY-SP'}
COL = {'DeFT': '#52514e', 'MTR': '#c0392b', 'RC': '#eb6834', 'DeFT_Dis': '#8e8d87', 'DeFT_Ran': '#b9b7af',
       'XY_SP': '#6b5b95', 'DeFT_OE_G': '#e0a800', 'CI_heurLA_G': '#4a3aa7', 'CI_qlLA_G': '#1baf7a',
       'FULL_qlLA_G': '#2a78d6'}
METRICS = [('latency', 'mean latency'), ('p99', 'p99 latency'), ('completion_cycles', 'cycles to complete both windows')]


def geo(xs):
    xs = [x for x in xs if x > 0 and not math.isnan(x)]
    return math.exp(sum(math.log(x) for x in xs) / len(xs)) if xs else float('nan')


def main():
    out = os.path.join(R15, 'report')
    os.makedirs(out, exist_ok=True)
    rows = list(csv.DictReader(open(os.path.join(R15, 'pair_runs.csv'))))
    bad = [r for r in rows if r['finished'] != 'True' or r['injected'] != r['delivered']]
    rows = [r for r in rows if r not in bad]
    R = {(r['pair'], r['method'], r['mask'], int(r['s']), int(r['seed'])): r for r in rows}
    pairs = sorted({r['pair'] for r in rows})
    masks = sorted({r['mask'] for r in rows})
    ss = sorted({int(r['s']) for r in rows})
    seeds = sorted({int(r['seed']) for r in rows})
    norm = []
    for s in ss:
        for m in masks:
            for pr in pairs:
                for v in METHODS:
                    vals = {}
                    for key, _ in METRICS:
                        vals[key] = geo([float(R[(pr, v, m, s, sd)][key]) / float(R[(pr, 'DeFT', m, s, sd)][key])
                                         for sd in seeds if (pr, v, m, s, sd) in R and (pr, 'DeFT', m, s, sd) in R])
                    if math.isnan(vals['latency']):
                        continue
                    offered = sum(float(R[(pr, v, m, s, sd)]['offered_flits_per_node_cycle']) for sd in seeds
                                  if (pr, v, m, s, sd) in R) / len(seeds)
                    norm.append(dict(s=s, mask=m, pair=pr, method=v, offered_flits_per_node_cycle=round(offered, 5),
                                     **{f'norm_{k}': round(x, 4) for k, x in vals.items()}))
    with open(os.path.join(out, 'normalised.csv'), 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(norm[0]), lineterminator='\n')
        w.writeheader()
        w.writerows(norm)
    L = ['# v15 two applications at once: normalised to DeFT(rho*) (generated by report_v15.py)', '',
         f'Runs: {len(rows) + len(bad)}; not finished or not drained (excluded): {len(bad)}. Ratios to DeFT(rho*) with '
         f'the same pair, s, mask and seed; geometric mean over seeds {", ".join(map(str, seeds))}.', '']
    for s in ss:
        for m in masks:
            ms = [v for v in METHODS if any(x['method'] == v and x['mask'] == m and x['s'] == s for x in norm)]
            tag = 'fault-free' if int(m, 16) == 0 else f'VL mask {m}'
            for key, title in METRICS:
                L += [f'## s = {s}, {tag}: {title} (DeFT(rho*) = 1)', '',
                      '| pair | ' + ' | '.join(LABEL.get(v, v) for v in ms) + ' |', '|---|' + '---|' * len(ms)]
                for pr in pairs:
                    cells = []
                    for v in ms:
                        x = next((y for y in norm if (y['s'], y['mask'], y['pair'], y['method']) == (s, m, pr, v)), None)
                        cells.append(f'{x["norm_" + key]:.3f}' if x else 'n/a')
                    L.append(f'| {pr} | ' + ' | '.join(cells) + ' |')
                L += ['| geometric mean | ' + ' | '.join(
                    f'**{geo([y["norm_" + key] for y in norm if (y["s"], y["mask"], y["method"]) == (s, m, v)]):.3f}**'
                    for v in ms) + ' |', '']
            L += [f'Offered load of DeFT(rho*) (flits per node and cycle over the completion time), s = {s}, {tag}: ' +
                  ', '.join(f'{pr} {next(y["offered_flits_per_node_cycle"] for y in norm if (y["s"], y["mask"], y["pair"], y["method"]) == (s, m, pr, "DeFT")):.4f}'
                            for pr in pairs), '']
            for key, title in METRICS:
                fig, ax = plt.subplots(figsize=(14, 4.4))
                wbar = 0.8 / len(ms)
                for i, v in enumerate(ms):
                    ys = [next((y['norm_' + key] for y in norm if (y['s'], y['mask'], y['pair'], y['method']) ==
                                (s, m, pr, v)), float('nan')) for pr in pairs]
                    ys.append(geo(ys))
                    ax.bar([j + (i - len(ms) / 2 + 0.5) * wbar for j in range(len(pairs) + 1)], ys, wbar * 0.95,
                           color=COL[v], label=LABEL.get(v, v))
                ax.axhline(1.0, color='#52514e', lw=0.8)
                ax.set_xticks(range(len(pairs) + 1))
                ax.set_xticklabels(pairs + ['geo. mean'], fontsize=8)
                ax.set_ylabel(f'{title} / DeFT(rho*)')
                ax.set_title(f'Two PARSEC applications at once (Netrace overlay), 2x2, s = {s}, {tag}: {title}', fontsize=10)
                ax.legend(frameon=False, fontsize=8, ncol=5)
                ax.grid(True, axis='y', color='#e6e5e1', lw=0.6)
                fig.tight_layout()
                for ext in ('png', 'pdf'):
                    fig.savefig(os.path.join(out, f'pairs_{key}_s{s}_{"fault-free" if int(m, 16) == 0 else m}.{ext}'),
                                dpi=125)
                plt.close(fig)
    if bad:
        L += ['## Excluded runs', ''] + [f'- {r["pair"]} {r["method"]} {r["mask"]} s {r["s"]} seed {r["seed"]}' for r in bad]
    open(os.path.join(out, 'summary.md'), 'w', newline='\n').write('\n'.join(L) + '\n')
    print('\n'.join(L[:80]))


if __name__ == '__main__':
    main()
