"""v8 step 1: the late-binding variants vs plain DeFT(rho*), following results_v8/PREREGISTRATION_step1.md.

Inputs (CSV only): results_v8/deft_runs.csv (DeFT(rho*), seeds 31-40; make_eval_csv.py results_v8 deft),
results_v6/eval_runs.csv (CI_heurLA, CI_qlLA, FULL_heurLA, FULL_qlLA, DeFT_tm(rho*)).
Outputs (results_v8/report_step1/): primary.csv, summary.md
"""
import csv
import os

from primary_from_csv import holm, ttest  # noqa: E402
from report_v4 import Data, load_csv, pct  # noqa: E402
import report_v5 as R5  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
R8 = os.path.join(HERE, 'results_v8')
SIZES = ['3x3', '4x4']
VARS = ['CI_heurLA', 'CI_qlLA', 'FULL_heurLA', 'FULL_qlLA']
METRICS = ['LAT', 'P99', 'THR']
SEEDS = range(31, 41)


def data():
    R = {k: v for k, v in load_csv(os.path.join(HERE, 'results_v6', 'eval_runs.csv')).items() if k[4] in SEEDS}
    R.update(load_csv(os.path.join(R8, 'deft_runs.csv')))
    return R, {z: Data(R, R5.scen(z), R5.ladder, SEEDS) for z in SIZES}


def main():
    out = os.path.join(R8, 'report_step1')
    os.makedirs(out, exist_ok=True)
    R, D = data()
    n_deft = sum(1 for k in R if k[0] == 'DeFT')
    expected = sum(len(R5.ladder(p, m)) for z in SIZES for p, m in R5.scen(z)) * len(SEEDS)
    missing = [(v, p, m, r, s) for z in SIZES for p, m in R5.scen(z) for r in R5.ladder(p, m) for s in SEEDS
               for v in ['DeFT'] + VARS + ['DeFT_tm'] if (v, p, m, r, s) not in R]
    prim = []
    for z in SIZES:
        for a in VARS:
            for n in METRICS:
                xs = D[z].per_seed(a, 'DeFT', n)
                e, lo, hi = pct(xs)
                tm = pct(D[z].per_seed(a, 'DeFT_tm', n))
                prim.append(dict(size=z, variant=a, reference='DeFT', metric=n, n_seeds=len(xs), effect_pct=round(e, 2),
                                 ci_low=round(lo, 2), ci_high=round(hi, 2), p=ttest(xs),
                                 capped_cells=D[z].capped(a, 'DeFT') if n == 'THR' else 0,
                                 vs_DeFT_tm_pct=round(tm[0], 2), vs_DeFT_tm_ci=f'[{tm[1]:+.2f}, {tm[2]:+.2f}]'))
    for x, q in zip(prim, holm([x['p'] for x in prim])):
        x['p_holm'] = q
        good = x['effect_pct'] > 0 if x['metric'] == 'THR' else x['effect_pct'] < 0
        x['verdict'] = ('better' if good else 'worse') if q < 0.05 else 'n.s.'
    with open(os.path.join(out, 'primary.csv'), 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(prim[0]), lineterminator='\n')
        w.writeheader()
        for x in prim:
            w.writerow({k: (f'{v:.4g}' if k in ('p', 'p_holm') else v) for k, v in x.items()})
    L = ['# v8 step 1 summary: late binding vs plain DeFT(rho*) (seeds 31-40; generated by report_v8_step1.py)', '',
         f'DeFT(rho*) runs: {n_deft} of {expected}; missing cells in any comparison: {len(missing)}. Variant runs and '
         'DeFT_tm(rho*) from results_v6/eval_runs.csv.', '',
         '## Primary results (pre-registered; Holm over 24 tests)', '',
         'Effect: mean over the 7 scenarios of the per-seed log ratio, % change, 95 % CI over seeds 31-40. Right-hand '
         'column: the v6 primary result of the same variant against DeFT_tm(rho*) (same variant runs).', '',
         '| size | variant | metric | vs DeFT(rho*): effect % [95 % CI] | p (Holm) | verdict | THR capped cells | '
         'v6: vs DeFT_tm(rho*) |', '|---|---|---|---|---|---|---|---|']
    for x in prim:
        L.append(f'| {x["size"]} | {x["variant"]} | {x["metric"]} | {x["effect_pct"]:+.2f} [{x["ci_low"]:+.2f}, '
                 f'{x["ci_high"]:+.2f}] | {x["p_holm"]:.3g} | **{x["verdict"]}** | '
                 f'{x["capped_cells"] if x["metric"] == "THR" else "-"} | {x["vs_DeFT_tm_pct"]:+.2f} {x["vs_DeFT_tm_ci"]} |')
    L += ['', '## Secondary: what traffic matching buys (DeFT_tm(rho*) vs DeFT(rho*), unadjusted)', '',
          '| size | metric | all scenarios | without chipperm |', '|---|---|---|---|']
    for z in SIZES:
        sc = [s for s in R5.scen(z) if 'chipperm' not in s[0]]
        for n in METRICS:
            e, lo, hi = pct(D[z].per_seed('DeFT_tm', 'DeFT', n))
            e2, lo2, hi2 = pct(D[z].per_seed('DeFT_tm', 'DeFT', n, sc))
            L.append(f'| {z} | {n} | {e:+.2f} [{lo:+.2f}, {hi:+.2f}] | {e2:+.2f} [{lo2:+.2f}, {hi2:+.2f}] |')
    L += ['', '## Secondary: saturation throughput without chipperm (unadjusted)', '',
          '| size | variant | vs DeFT(rho*) | vs DeFT_tm(rho*) |', '|---|---|---|---|']
    for z in SIZES:
        sc = [s for s in R5.scen(z) if 'chipperm' not in s[0]]
        for a in VARS:
            e, lo, hi = pct(D[z].per_seed(a, 'DeFT', 'THR', sc))
            e2, lo2, hi2 = pct(D[z].per_seed(a, 'DeFT_tm', 'THR', sc))
            L.append(f'| {z} | {a} | {e:+.2f} [{lo:+.2f}, {hi:+.2f}] | {e2:+.2f} [{lo2:+.2f}, {hi2:+.2f}] |')
    L.append('')
    for n in METRICS:
        L += [f'## Secondary: per-scenario {n} vs DeFT(rho*) (unadjusted; `°` = CI excludes 0; `≥` = capped)', '']
        for z in SIZES:
            sc = R5.scen(z)
            L += [f'**{z}**', '', '| comparison | ' + ' | '.join(f'{p.split("-")[1]} {m}' for p, m in sc) + ' |',
                  '|---|' + '---|' * len(sc)]
            for a in VARS + ['DeFT_tm']:
                cells = []
                for p, m in sc:
                    e, lo, hi = pct(D[z].per_seed(a, 'DeFT', n, [(p, m)]))
                    capped = n == 'THR' and any(D[z].thr(a, p, m, s)[1] or D[z].thr('DeFT', p, m, s)[1] for s in SEEDS)
                    cells.append(f'{"≥" if capped else ""}{e:+.1f}{"°" if hi < 0 or lo > 0 else ""}')
                L.append(f'| {a} vs DeFT | ' + ' | '.join(cells) + ' |')
            L.append('')
    if missing:
        L += ['## Missing cells', ''] + [f'- {m}' for m in missing[:50]] + ['']
    open(os.path.join(out, 'summary.md'), 'w', newline='\n').write('\n'.join(L) + '\n')
    print(f'DeFT runs {n_deft}/{expected}, missing {len(missing)}')
    for x in prim:
        print(x['size'], x['variant'], x['metric'], x['effect_pct'], x['ci_low'], x['ci_high'], f'{x["p_holm"]:.3g}',
              x['verdict'], '| vs DeFT_tm', x['vs_DeFT_tm_pct'])


if __name__ == '__main__':
    main()
