"""v7 step 2: bottleneck statistics with the v6 tuned parameters and the chosen entry bounds (descriptive).

Same measurement as v6 step 1 (bottleneck_v6.py): 4x4 uniform and localized fault-free; loads 0.8, 1.0, 1.2 x Lsat
(v5 load points); seeds 101-103; statistics flag on. Variants: DeFT_tm(rho*) through its traffic-identical DEFT_LB
proxy, CI_heurLA and CI_qlLA with the v6 tuned parameters, and CI_heurLA_B / CI_qlLA_B (the step 3 choice).
Side by side with v6 (results_v6/bottleneck_agg.json: DeFT_tm, CI_heurLA and FULL_heurLA with the v5 parameters).
Centre concentration: interposer links with both ends in the central 8x8 routers vs the rest; entry (up) VLs whose
endpoint lies in the central 8x8 routers vs the others.
Usage: python3 bottleneck_v7.py run [nproc]
       python3 bottleneck_v7.py analyze [cleanup]
"""
import json
import os
import shutil
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from runner import common_args, run_jobs  # noqa: E402
import variants as V  # noqa: E402
import experiments_v5 as E5  # noqa: E402
import experiments_v6 as E6  # noqa: E402
import experiments_v7 as E7  # noqa: E402
import bottleneck_v6 as B6  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
R7 = os.path.join(HERE, 'results_v7')
RAW = os.path.join(R7, 'bottleneck_raw')
SIZE = '4x4'
SCEN = B6.SCEN
LOADS = B6.LOADS
SEEDS = B6.SEEDS
CLASSES = B6.CLASSES
W = 16
ORDER = ['DeFT_tm', 'CI_heurLA', 'CI_qlLA', 'CI_heurLA_B', 'CI_qlLA_B']


def variants():
    tv = E7.variants(SIZE)
    out = {'DeFT_tm': (V.inj('lut'), E6.variant_lut(SIZE, 'DeFT_tm', 'uniform'))}
    for v in ORDER[1:]:
        out[v] = (tv[v], E6.exit_lut(SIZE))
    return out


def jobs():
    js = []
    for (p, m), (ld, i), (v, (va, lut)), s in [(a, b, c, d) for a in SCEN for b in LOADS.items()
                                                for c in variants().items() for d in SEEDS]:
        # DeFT_tm's LUT for localized is the uniform one (v5: localized gives exactly the uniform LUT), as in v6
        rate = E6.LP5[f'{SIZE}__{p}__{m}']['eval'][i]
        name = f'bn__{v}__{p}__{ld}__s{s}'
        args = common_args(s, m, traffic=E5.REL + f'traffic_{SIZE}/{p}_{rate:.4f}.txt', lut=lut) + \
            E5.size_args(SIZE) + va + E5.SIM + ['-deft_lb', 'stats_file', os.path.join(RAW, name + '.stats.json')]
        js.append((name, args))
    return js


def centre(x, y):
    return 4 <= x <= 11 and 4 <= y <= 11


def metrics(a):
    """Summary numbers of one aggregated cell (bottleneck_v6.analyze format)."""
    def mean(xs):
        return sum(xs) / len(xs) if xs else float('nan')
    links = {k: u for k, u in a['link'].items() if B6._exists(k)}
    chip = [u for k, u in links.items() if k.startswith('chip')]
    ip_c, ip_o = [], []
    for k, u in links.items():
        if not k.startswith('ipos'):
            continue
        _, x, y, d = k.split(',')
        x, y, d = int(x), int(y), int(d)
        dx, dy = {0: (0, -1), 1: (1, 0), 2: (0, 1), 3: (-1, 0)}[d]
        (ip_c if centre(x, y) and centre(x + dx, y + dy) else ip_o).append(u)
    up = {k: u for k, u in a['vl'].items() if k.startswith('up')}
    down = [u for k, u in a['vl'].items() if k.startswith('down')]
    up_c = [u for k, u in up.items() if centre(int(k.split(',')[1]), int(k.split(',')[2]))]
    up_o = [u for k, u in up.items() if not centre(int(k.split(',')[1]), int(k.split(',')[2]))]
    ex = {int(k): c for k, c in a['extra'].items()}
    tot = sum(ex.values())
    res = {}
    for c in CLASSES:
        h, rs, _ = a['class'][c]
        res[c] = rs / h if h else float('nan')
    return dict(chip=mean(chip), ipos=mean(ip_c + ip_o), ipos_c=mean(ip_c), ipos_o=mean(ip_o),
                ipos_ratio=mean(ip_c) / mean(ip_o), up_maxmean=max(up.values()) / mean(list(up.values())),
                down_maxmean=max(down) / mean(down), up_c=mean(up_c), up_o=mean(up_o), up_ratio=mean(up_c) / mean(up_o),
                entry_diff=100 * a['entry_diff'] / a['lut_known'], extra_mean=sum(k * c for k, c in ex.items()) / tot,
                extra_share=100 * sum(c for k, c in ex.items() if k > 0) / tot, res=res,
                lat=mean(a['latency']), acc=mean(a['accepted']), runs=a['runs'])


def analyze():
    B6.RAW, B6.R6 = RAW, R7               # reuse the v6 aggregation; writes results_v7/bottleneck_agg.json
    return B6.analyze()


def report(agg):
    v6 = json.load(open(os.path.join(HERE, 'results_v6', 'bottleneck_agg.json')))
    L = ['# v7 step 2: bottleneck statistics with the tuned parameters and the entry bound (4x4, fault-free)', '',
         'Generated by bottleneck_v7.py. Same measurement as v6 step 1 (`results_v6/bottleneck.md`): statistics flag on, '
         'averages over seeds 101-103, v5 load points. v7 rows: DeFT_tm(rho*) (DEFT_LB proxy), CI_heurLA and CI_qlLA with '
         'the v6 tuned parameters, and the bounded CI_heurLA_B / CI_qlLA_B (`selection_choice.json`). v6 rows (from '
         '`results_v6/bottleneck_agg.json`): CI_heurLA and FULL_heurLA with the v5 (2x2-tuned) parameters.', '',
         'Columns: link loads in flits/cycle per link direction (means). "centre / rest" = mean load of interposer links '
         'with both ends in the central 8x8 routers over the mean of all other interposer links. Entry VL = up VL '
         '(interposer to destination chiplet); "central / rest" = mean load of the up VLs whose endpoint lies in the '
         'central 8x8 routers over the others. "entry differs" = share of inter-chiplet packets whose entry VL differs from the uniform '
         'DeFT(rho*) LUT\'s (for the DeFT_tm proxy: its own LUT, 0 by construction). Extra hops: against the LUT path.', '']
    cells = [('v6', v, v6) for v in ('DeFT_tm', 'CI_heurLA', 'FULL_heurLA')] + [('v7', v, agg) for v in ORDER]
    for p, _ in SCEN:
        for ld in LOADS:
            L += [f'## {p}, {ld} x Lsat', '',
                  '| run | variant | interposer links | centre / rest | chiplet links | entry VL max/mean | entry VL central / rest | '
                  'exit VL max/mean | entry differs | extra hops: mean / share > 0 | mean latency | accepted |',
                  '|---|---|---|---|---|---|---|---|---|---|---|---|']
            for tag, v, src in cells:
                k = f'{v}|{p}|{ld}'
                if k not in src:
                    continue
                x = metrics(src[k])
                L.append(f'| {tag} | {v} | {x["ipos"]:.3f} | {x["ipos_ratio"]:.2f} | {x["chip"]:.3f} | {x["up_maxmean"]:.2f} | '
                         f'{x["up_ratio"]:.2f} | {x["down_maxmean"]:.2f} | {x["entry_diff"]:.1f} % | '
                         f'{x["extra_mean"]:+.2f} / {x["extra_share"]:.0f} % | {x["lat"]:.1f} | {x["acc"]:.4f} |')
            L.append('')
            L += ['Head-flit buffer residence per hop (cycles): ' + ', '.join(CLASSES), '',
                  '| run | variant | ' + ' | '.join(CLASSES) + ' |', '|---|---|' + '---|' * len(CLASSES)]
            for tag, v, src in cells:
                k = f'{v}|{p}|{ld}'
                if k not in src:
                    continue
                x = metrics(src[k])
                L.append(f'| {tag} | {v} | ' + ' | '.join(f'{x["res"][c]:.1f}' for c in CLASSES) + ' |')
            L.append('')
    open(os.path.join(R7, 'bottleneck_tables.md'), 'w', newline='\n').write('\n'.join(L) + '\n')
    print('\n'.join(L))
    out = {f'{tag}|{v}|{p}|{ld}': {k: val for k, val in metrics(src[f'{v}|{p}|{ld}']).items()}
           for tag, v, src in cells for p, _ in SCEN for ld in LOADS if f'{v}|{p}|{ld}' in src}
    json.dump(out, open(os.path.join(R7, 'bottleneck_metrics.json'), 'w'), indent=1)
    heatmap(agg)


def heatmap(agg):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    from matplotlib import cm, colors
    for p, _ in SCEN:
        fig, axes = plt.subplots(1, len(ORDER), figsize=(4.2 * len(ORDER), 4.6))
        vmax = max(max(agg[f'{v}|{p}|1.0']['link'].values()) for v in ORDER)
        norm = colors.Normalize(0, vmax)
        cmap = matplotlib.colormaps['viridis']
        for ax, v in zip(axes, ORDER):
            a = agg[f'{v}|{p}|1.0']
            for x in range(W):
                for y in range(W):
                    for dirn, (dx, dy) in ((1, (1, 0)), (2, (0, 1))):
                        x2, y2 = x + dx, y + dy
                        if x2 >= W or y2 >= W:
                            continue
                        back = 3 if dirn == 1 else 0
                        u = max(a['link'].get(f'ipos,{x},{y},{dirn}', 0.0), a['link'].get(f'ipos,{x2},{y2},{back}', 0.0))
                        ax.plot([x, x2], [y, y2], color=cmap(norm(u)), lw=3.0, solid_capstyle='butt')
            for k, u in a['vl'].items():
                d, x, y = k.split(',')
                if d == 'up':
                    ax.scatter([int(x)], [int(y)], s=55, color=cmap(norm(u)), edgecolors='#c0392b', linewidths=1.2, zorder=3)
            ax.add_patch(plt.Rectangle((3.5, 3.5), 8, 8, fill=False, ls='--', lw=0.8, ec='#888'))
            ax.set_xlim(-0.6, W - 0.4)
            ax.set_ylim(W - 0.4, -0.6)
            ax.set_aspect('equal')
            ax.set_xticks([])
            ax.set_yticks([])
            ax.set_title(f'{v}: interposer (entry VLs marked)', fontsize=9)
        fig.colorbar(cm.ScalarMappable(norm=norm, cmap=cmap), ax=axes, shrink=0.7,
                     label='flits/cycle (link: max of the two directions)')
        fig.suptitle(f'4x4 {p}, fault-free, 1.0 x Lsat, mean over seeds 101-103 (dashed: central 8x8)', fontsize=10)
        fig.savefig(os.path.join(R7, f'bottleneck_links_{p}.png'), dpi=105)
        plt.close(fig)


if __name__ == '__main__':
    if sys.argv[1] == 'run':
        os.makedirs(RAW, exist_ok=True)
        res = run_jobs(jobs(), RAW, nproc=int(sys.argv[2]) if len(sys.argv) > 2 else 12, timeout=7200)
        print('runs', len(res), 'missing', sum(1 for v in res.values() if v is None))
    else:
        agg = analyze()
        report(agg)
        if len(sys.argv) > 2 and sys.argv[2] == 'cleanup':
            shutil.rmtree(RAW)
            print('raw outputs deleted')
