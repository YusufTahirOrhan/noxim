"""v8 step 4: bottleneck statistics of the gamma-weighted variants (descriptive).

Same measurement as v7 step 2 (bottleneck_v7.py): 4x4 uniform and localized fault-free; loads 0.8, 1.0, 1.2 x Lsat;
seeds 101-103; statistics flag on. New runs: CI_heurLA_G, CI_qlLA_G, FULL_qlLA_G (step 3 choice) and the FULL_qlLA
parent (not in v7). DeFT_tm(rho*), CI_heurLA and CI_qlLA come from results_v7/bottleneck_agg.json (same runs; the
binary with gamma = 1 is identical to v7's).
Usage: python3 bottleneck_v8.py run [nproc]
       python3 bottleneck_v8.py analyze [cleanup]
"""
import json
import os
import shutil
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from runner import common_args, run_jobs  # noqa: E402
import experiments_v5 as E5  # noqa: E402
import experiments_v6 as E6  # noqa: E402
import experiments_v8 as E8  # noqa: E402
import bottleneck_v6 as B6  # noqa: E402
import bottleneck_v7 as B7  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
R8 = os.path.join(HERE, 'results_v8')
RAW = os.path.join(R8, 'bottleneck_raw')
SIZE = '4x4'
NEW = ['CI_heurLA_G', 'CI_qlLA_G', 'FULL_qlLA', 'FULL_qlLA_G']
ROWS = [('v7', 'DeFT_tm'), ('v7', 'CI_heurLA'), ('v8', 'CI_heurLA_G'), ('v7', 'CI_qlLA'), ('v8', 'CI_qlLA_G'),
        ('v8', 'FULL_qlLA'), ('v8', 'FULL_qlLA_G')]
PARENT = {'CI_heurLA_G': 'CI_heurLA', 'CI_qlLA_G': 'CI_qlLA', 'FULL_qlLA_G': 'FULL_qlLA'}


def jobs():
    tv = E8.variants(SIZE)
    js = []
    for (p, m), (ld, i), v, s in [(a, b, c, d) for a in B6.SCEN for b in B6.LOADS.items() for c in NEW for d in B6.SEEDS]:
        rate = E6.LP5[f'{SIZE}__{p}__{m}']['eval'][i]
        name = f'bn__{v}__{p}__{ld}__s{s}'
        args = common_args(s, m, traffic=E5.REL + f'traffic_{SIZE}/{p}_{rate:.4f}.txt', lut=E6.exit_lut(SIZE)) + \
            E5.size_args(SIZE) + tv[v] + E5.SIM + ['-deft_lb', 'stats_file', os.path.join(RAW, name + '.stats.json')]
        js.append((name, args))
    return js


def report(agg8):
    agg7 = json.load(open(os.path.join(HERE, 'results_v7', 'bottleneck_agg.json')))
    src = {'v7': agg7, 'v8': agg8}
    ch = json.load(open(os.path.join(R8, 'selection_choice.json')))
    L = ['# v8 step 4: bottleneck statistics of the gamma-weighted variants (4x4, fault-free)', '',
         'Generated by bottleneck_v8.py. Measurement as v6 step 1 / v7 step 2 (statistics flag on, averages over seeds '
         '101-103, v5 load points). v8 rows: ' + ', '.join(f'{p}_G (gamma {ch[p]["gamma"]})' for p in E8.PARENTS) +
         ', and the FULL_qlLA parent (gamma 1). v7 rows (results_v7/bottleneck_agg.json): DeFT_tm(rho*) (DEFT_LB proxy), '
         'CI_heurLA and CI_qlLA (gamma 1). Columns as in results_v7/bottleneck_tables.md.', '']
    for p, _ in B6.SCEN:
        for ld in B6.LOADS:
            L += [f'## {p}, {ld} x Lsat', '',
                  '| run | variant | interposer links | centre / rest | chiplet links | entry VL max/mean | exit VL max/mean | '
                  'entry differs | extra hops: mean / share > 0 | mean latency | accepted |',
                  '|---|---|---|---|---|---|---|---|---|---|---|']
            for tag, v in ROWS:
                x = B7.metrics(src[tag][f'{v}|{p}|{ld}'])
                L.append(f'| {tag} | {v} | {x["ipos"]:.3f} | {x["ipos_ratio"]:.2f} | {x["chip"]:.3f} | {x["up_maxmean"]:.2f} | '
                         f'{x["down_maxmean"]:.2f} | {x["entry_diff"]:.1f} % | {x["extra_mean"]:+.2f} / {x["extra_share"]:.0f} % | '
                         f'{x["lat"]:.1f} | {x["acc"]:.4f} |')
            L += ['', '| run | variant | ' + ' | '.join(f'{c} residence' for c in B6.CLASSES) + ' |',
                  '|---|---|' + '---|' * len(B6.CLASSES)]
            for tag, v in ROWS:
                x = B7.metrics(src[tag][f'{v}|{p}|{ld}'])
                L.append(f'| {tag} | {v} | ' + ' | '.join(f'{x["res"][c]:.1f}' for c in B6.CLASSES) + ' |')
            L.append('')
    # closeness of the interposer load to DeFT_tm's (uniform, 1.0 x Lsat) for the pre-registered verdict
    L += ['## Interposer link load: distance to DeFT_tm(rho*) (pre-registered criterion, 4x4)', '',
          '| pattern | load | variant | interposer load | parent\'s | DeFT_tm\'s | |variant - DeFT_tm| < |parent - DeFT_tm| |',
          '|---|---|---|---|---|---|---|']
    out = {}
    for p, _ in B6.SCEN:
        for ld in B6.LOADS:
            ref = B7.metrics(agg7[f'DeFT_tm|{p}|{ld}'])['ipos']
            for v, par in PARENT.items():
                x = B7.metrics(agg8[f'{v}|{p}|{ld}'])['ipos']
                ps = agg7 if par in ('CI_heurLA', 'CI_qlLA') else agg8
                y = B7.metrics(ps[f'{par}|{p}|{ld}'])['ipos']
                closer = abs(x - ref) < abs(y - ref)
                out[f'{v}|{p}|{ld}'] = dict(variant=x, parent=y, deft_tm=ref, closer=closer)
                L.append(f'| {p} | {ld} | {v} | {x:.4f} | {y:.4f} | {ref:.4f} | {"yes" if closer else "no"} |')
    L.append('')
    json.dump(out, open(os.path.join(R8, 'bottleneck_closeness.json'), 'w'), indent=1)
    met = {f'{tag}|{v}|{p}|{ld}': B7.metrics(src[tag][f'{v}|{p}|{ld}'])
           for tag, v in ROWS for p, _ in B6.SCEN for ld in B6.LOADS}
    json.dump(met, open(os.path.join(R8, 'bottleneck_metrics.json'), 'w'), indent=1)
    open(os.path.join(R8, 'bottleneck_tables.md'), 'w', newline='\n').write('\n'.join(L) + '\n')
    print('\n'.join(L))
    B7.ORDER, B7.R7 = ['CI_heurLA_G', 'CI_qlLA_G', 'FULL_qlLA', 'FULL_qlLA_G'], R8
    B7.heatmap(agg8)


if __name__ == '__main__':
    if sys.argv[1] == 'run':
        os.makedirs(RAW, exist_ok=True)
        res = run_jobs(jobs(), RAW, nproc=int(sys.argv[2]) if len(sys.argv) > 2 else 12, timeout=7200)
        print('runs', len(res), 'missing', sum(1 for v in res.values() if v is None))
    else:
        B6.RAW, B6.R6 = RAW, R8
        agg = B6.analyze()
        report(agg)
        if len(sys.argv) > 2 and sys.argv[2] == 'cleanup':
            shutil.rmtree(RAW)
            print('raw outputs deleted')
