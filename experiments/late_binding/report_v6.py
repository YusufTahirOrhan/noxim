"""Analysis of v6 (proposed methods tuned per size), following results_v6/PREREGISTRATION.md.

Inputs (CSV only): results_v6/eval_runs.csv (make_eval_csv.py results_v6 eval), results_v5/load_points.json,
results_v5/eval_runs.csv (untuned parameters, seeds 21-30, for the side-by-side and the 2x2 point).
Outputs (results_v6/report/): primary.csv, summary.md, effect_vs_size.png
Usage: python3 report_v6.py [first]
"""
import csv
import math
import os
import sys

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt  # noqa: E402

from primary_from_csv import holm, ttest  # noqa: E402
from report_v4 import Data, load_csv, pct  # noqa: E402
import report_v5 as R5  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
R6 = os.path.join(HERE, 'results_v6')
SIZES = ['3x3', '4x4']
VS_REF = [('CI_heurLA', 'DeFT_tm'), ('CI_qlLA', 'DeFT_tm'), ('FULL_heurLA', 'DeFT_tm'), ('FULL_qlLA', 'DeFT_tm')]
LEARN = [('CI_qlLA', 'CI_heurLA'), ('FULL_qlLA', 'FULL_heurLA')]
METRICS = ['LAT', 'P99', 'THR']
CSTYLE = {'CI_heurLA': '#4a3aa7', 'CI_qlLA': '#1baf7a', 'FULL_heurLA': '#eb6834', 'FULL_qlLA': '#2a78d6'}
CHIPLETS = {'2x2': 4, '3x3': 9, '4x4': 16}


def main():
    first = len(sys.argv) > 1 and sys.argv[1] == 'first'
    seeds = range(31, 36) if first else range(31, 41)
    out = os.path.join(R6, 'report_seeds31-35' if first else 'report')
    os.makedirs(out, exist_ok=True)
    R = {k: v for k, v in load_csv(os.path.join(R6, 'eval_runs.csv')).items() if k[4] in seeds}
    D = {z: Data(R, R5.scen(z), R5.ladder, seeds) for z in SIZES}
    dead = sum(x['dead'] for x in R.values())
    expected = sum(len(R5.ladder(p, m)) for z in SIZES for p, m in R5.scen(z)) * 5 * len(seeds)
    V5 = load_csv(os.path.join(HERE, 'results_v5', 'eval_runs.csv'))
    U = {z: Data(V5, R5.scen(z), R5.ladder, range(21, 31)) for z in ['2x2'] + SIZES}

    def untuned(z, a, b, n):
        try:
            return pct(U[z].per_seed(a, b, n))
        except (KeyError, ZeroDivisionError, ValueError):
            return None

    prim = []
    for z in SIZES:
        for a, b in VS_REF + LEARN:
            for n in METRICS:
                xs = D[z].per_seed(a, b, n)
                e, lo, hi = pct(xs)
                u = untuned(z, a, b, n)
                prim.append(dict(size=z, variant=a, reference=b, metric=n, n_seeds=len(xs), effect_pct=round(e, 2),
                                 ci_low=round(lo, 2), ci_high=round(hi, 2), p=ttest(xs),
                                 capped_cells=D[z].capped(a, b) if n == 'THR' else 0,
                                 untuned_v5_effect_pct=round(u[0], 2) if u else ''))
    for x, q in zip(prim, holm([x['p'] for x in prim])):
        x['p_holm'] = q
        good = x['effect_pct'] > 0 if x['metric'] == 'THR' else x['effect_pct'] < 0
        x['verdict'] = ('better' if good else 'worse') if q < 0.05 else 'n.s.'
    with open(os.path.join(out, 'primary.csv'), 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(prim[0]), lineterminator='\n')
        w.writeheader()
        for x in prim:
            w.writerow({k: (f'{v:.4g}' if k in ('p', 'p_holm') else v) for k, v in x.items()})

    L = [f'# v6 summary (seeds {min(seeds)}-{max(seeds)}; generated by report_v6.py)', '',
         f'Runs: {len(R)} of {expected}; dead-end events: {dead}.', '',
         '## Primary results (pre-registered; Holm over 36 tests)', '',
         'Effect: mean over the 7 scenarios of the size of the per-seed log ratio, % change, 95 % CI over seeds 31-40. '
         '"v5 untuned" = the same comparison with the 2x2-tuned parameters (results_v5, seeds 21-30); FULL_qlLA was '
         'not run in v5.', '',
         '| size | variant | reference | metric | v6 tuned: effect % [95 % CI] | p (Holm) | verdict | THR capped cells | v5 untuned |',
         '|---|---|---|---|---|---|---|---|---|']
    for x in prim:
        u = x['untuned_v5_effect_pct']
        L.append(f'| {x["size"]} | {x["variant"]} | {x["reference"]} | {x["metric"]} | {x["effect_pct"]:+.2f} '
                 f'[{x["ci_low"]:+.2f}, {x["ci_high"]:+.2f}] | {x["p_holm"]:.3g} | **{x["verdict"]}** | '
                 f'{x["capped_cells"] if x["metric"] == "THR" else "-"} | {f"{u:+.2f}" if u != "" else "n/a"} |')
    L.append('')

    L += ['## Secondary: saturation throughput without chipperm (unadjusted)', '', '| size | comparison | THR w/o chipperm |',
          '|---|---|---|']
    for z in SIZES:
        sc = [s for s in R5.scen(z) if 'chipperm' not in s[0]]
        for a, b in VS_REF + LEARN:
            e, lo, hi = pct(D[z].per_seed(a, b, 'THR', sc))
            L.append(f'| {z} | {a} vs {b} | {e:+.2f} [{lo:+.2f}, {hi:+.2f}] |')
    L.append('')

    for n in METRICS:
        L += [f'## Secondary: per-scenario {n} (unadjusted; `°` = CI excludes 0; `≥` = capped)', '']
        for z in SIZES:
            sc = R5.scen(z)
            L += [f'**{z}**', '', '| comparison | ' + ' | '.join(f'{p.split("-")[1]} {m}' for p, m in sc) + ' |',
                  '|---|' + '---|' * len(sc)]
            for a, b in VS_REF + LEARN:
                cells = []
                for p, m in sc:
                    e, lo, hi = pct(D[z].per_seed(a, b, n, [(p, m)]))
                    capped = n == 'THR' and any(D[z].thr(a, p, m, s)[1] or D[z].thr(b, p, m, s)[1] for s in seeds)
                    cells.append(f'{"≥" if capped else ""}{e:+.1f}{"°" if hi < 0 or lo > 0 else ""}')
                L.append(f'| {a} vs {b} | ' + ' | '.join(cells) + ' |')
            L.append('')

    L += ['## Secondary: VL usage imbalance (max/mean over functional VLs) at ~1.0 x Lsat, mean over seeds', '',
          'DeFT_tm(rho*) from the traffic-identical proxy.', '']
    for z in SIZES:
        sc = R5.scen(z)
        L += [f'**{z}**', '', '| variant | ' + ' | '.join(f'{p.split("-")[1]} {m}' for p, m in sc) + ' |',
              '|---|' + '---|' * len(sc)]
        for v in ('DeFT_tm', 'CI_heurLA', 'CI_qlLA', 'FULL_heurLA', 'FULL_qlLA'):
            cells = []
            for p, m in sc:
                r = R5.ladder(p, m)[3]
                xs = [R[(v, p, m, r, s)]['imb'] for s in seeds if (v, p, m, r, s) in R]
                xs = [x for x in xs if not math.isnan(x)]
                cells.append(f'{sum(xs) / len(xs):.2f}' if xs else 'n/a')
            L.append(f'| {v} | ' + ' | '.join(cells) + ' |')
        L.append('')
    open(os.path.join(out, 'summary.md'), 'w', newline='\n').write('\n'.join(L) + '\n')

    # ---- figure ----
    fig, axes = plt.subplots(1, 3, figsize=(16, 4.8))
    titles = {'LAT': 'Mean latency at 1.0 x Lsat (lower is better)', 'P99': 'p99 latency at 1.0 x Lsat (lower is better)',
              'THR': 'Saturation throughput (higher is better)'}
    for ax, n in zip(axes, METRICS):
        for j, (a, b) in enumerate(VS_REF):
            col = CSTYLE[a]
            off = (j - 1.5) * 0.25
            ux, uy = [], []
            for z in ['2x2'] + SIZES:
                u = untuned(z, a, b, n)
                if u:
                    ux.append(CHIPLETS[z] + off - 0.1)
                    uy.append(u)
            if ux:
                ax.errorbar(ux, [y[0] for y in uy], yerr=[[y[0] - y[1] for y in uy], [y[2] - y[0] for y in uy]],
                            fmt='o:', mfc='white', color=col, capsize=2, ms=5, lw=1)
            pts = [x for x in prim if x['variant'] == a and x['reference'] == b and x['metric'] == n]
            ax.errorbar([CHIPLETS[x['size']] + off + 0.1 for x in pts], [x['effect_pct'] for x in pts],
                        yerr=[[x['effect_pct'] - x['ci_low'] for x in pts], [x['ci_high'] - x['effect_pct'] for x in pts]],
                        fmt='o-', color=col, capsize=2, ms=6, lw=1.6, label=f'{a} vs DeFT_tm(rho*)')
        ax.axhline(0, color='#52514e', lw=0.8)
        ax.set_xticks([4, 9, 16])
        ax.set_xticklabels(['4 (2x2)\nv5 only', '9 (3x3)', '16 (4x4)'])
        ax.set_xlabel('chiplets')
        ax.set_ylabel('% change vs DeFT_tm(rho*), mean over scenarios')
        ax.set_title(titles[n], fontsize=10)
        ax.grid(True, axis='y', color='#e6e5e1', lw=0.6)
        for sp in ('top', 'right'):
            ax.spines[sp].set_visible(False)
    h, lab = axes[0].get_legend_handles_labels()
    fig.legend(h, lab, loc='lower center', ncol=4, frameon=False, fontsize=9)
    fig.suptitle('Effects vs size against the tuned baseline. Hollow, dotted: 2x2-tuned parameters (v5, seeds 21-30). '
                 'Filled, solid: parameters tuned per size (v6, seeds 31-40). 95 % CI over seeds.', fontsize=9)
    fig.tight_layout(rect=(0, 0.07, 1, 1))
    fig.savefig(os.path.join(out, 'effect_vs_size.png'), dpi=130)
    plt.close(fig)
    print(f'runs {len(R)}/{expected}, dead {dead}')
    for x in prim:
        print(x['size'], x['variant'], 'vs', x['reference'], x['metric'], x['effect_pct'], x['ci_low'], x['ci_high'],
              f'{x["p_holm"]:.3g}', x['verdict'], 'v5:', x['untuned_v5_effect_pct'])


if __name__ == '__main__':
    main()
