"""v12 (Part D): energy per delivered flit with Noxim's power model (results_v12_energy/).

Stages (python3 experiments_v12.py STAGE [nproc]):
  powercheck  -power on vs the default run for 3 methods x 3 sizes (summary block must be identical)
  energy      uniform fault-free, 0.5 and 1.0 x Lsat, seeds 41-43, all methods, all sizes; warm-up 0 so that energy and
              delivered flits cover the same 10000 cycles -> results_v12_energy/energy_runs.csv, report/energy.{md,png,pdf}
Power model: bin/power.yaml (Noxim's default; loaded on every run). VL hops are charged as router-to-hub links of the
configured length; static energy is charged to every router every cycle. The RC buffer is not part of the model.
"""
import csv
import json
import math
import os
import shutil
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from runner import BIN, ENV, run_jobs  # noqa: E402
import experiments_v5 as E5  # noqa: E402
import experiments_v10 as E10  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, 'results_v12_energy')
SIZES = ['2x2', '3x3', '4x4']
METHODS = ['DeFT', 'MTR', 'RC', 'DeFT_Dis', 'DeFT_Ran', 'XY_SP', 'DeFT_OE_G', 'CI_heurLA_G', 'CI_qlLA_G', 'FULL_qlLA_G']
LOADS = {'0.5': 1, '1.0': 3}
SEEDS = (41, 42, 43)
LABEL = {'DeFT': 'DeFT(rho*)', 'DeFT_Dis': 'DeFT-Dis', 'DeFT_Ran': 'DeFT-Ran', 'XY_SP': 'XY-SP'}


def raw(stage):
    return os.path.join(RES, stage + '_raw')


def job(stage, size, v, ld, s, extra=()):
    p, m = 'uniform', E5.FREE[size]
    r = E10.LP5[f'{size}__{p}__{m}']['eval'][LOADS[ld]]
    n, a = E5.job(stage, size, v, E10.methods(size)[v], p, m, r, s, E10.lut(size, v, p))
    a = [x for x in a]
    k = a.index('-warmup')
    a[k + 1] = '0'
    return n, a + list(extra)


def powercheck(nproc):
    js = []
    for size in SIZES:
        for v in ('DeFT', 'RC', 'FULL_qlLA_G'):
            n, a = job('pc', size, v, '1.0', 41)
            js.append((n + '__off', a))
            js.append((n + '__on', a + ['-power', os.path.join(BIN, 'power.yaml')]))
    res = run_jobs(js, raw('powercheck'), nproc=nproc, timeout=7200)
    ok = sum(1 for n, _ in js if n.endswith('__off') and res[n] and res[n.replace('__off', '__on')] and
             res[n]['summary'] == res[n.replace('__off', '__on')]['summary'])
    shutil.rmtree(raw('powercheck'))
    return ok, len(js) // 2


def energy(nproc):
    js = [job('en', size, v, ld, s) for size in SIZES for v in METHODS for ld in LOADS for s in SEEDS]
    res = run_jobs(js, raw('energy'), nproc=nproc, timeout=7200)
    rows = []
    for size in SIZES:
        for v in METHODS:
            for ld in LOADS:
                for s in SEEDS:
                    n, _ = job('en', size, v, ld, s)
                    d = res[n]['summary']
                    f = d['total_received_flits']
                    rows.append(dict(size=size, method=v, load=ld, seed=s, received_flits=f,
                                     latency=repr(d['global_average_delay_cycles']),
                                     dynamic_j=repr(d['dynamic_energy_j']), static_j=repr(d['static_energy_j']),
                                     total_j=repr(d['total_energy_j']),
                                     dynamic_pj_per_flit=repr(1e12 * d['dynamic_energy_j'] / f),
                                     static_pj_per_flit=repr(1e12 * d['static_energy_j'] / f),
                                     total_pj_per_flit=repr(1e12 * d['total_energy_j'] / f)))
    with open(os.path.join(RES, 'energy_runs.csv'), 'w', newline='') as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]), lineterminator='\n')
        w.writeheader()
        w.writerows(rows)
    shutil.rmtree(raw('energy'))
    return rows


def report(rows, pc):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    out = os.path.join(RES, 'report')
    os.makedirs(out, exist_ok=True)

    def mean(size, v, ld, key):
        xs = [float(r[key]) for r in rows if (r['size'], r['method'], r['load']) == (size, v, ld)]
        return sum(xs) / len(xs)
    L = ['# v12 energy per delivered flit (Noxim power model; generated by experiments_v12.py)', '',
         f'-power on vs off: {pc[0]} / {pc[1]} runs with identical summary blocks (latency, throughput, energy).', '',
         'Uniform, fault-free; mean over seeds 41-43; 10000 cycles with warm-up 0 (energy and delivered flits over the '
         'same interval). pJ per delivered flit; in brackets: % against DeFT(rho*). Static energy is charged to every '
         'router every cycle, so its share per flit falls with the delivered traffic; the RC buffer is not modelled.', '']
    for ld in LOADS:
        L += [f'## {ld} x Lsat', '', '| method | ' + ' | '.join(f'{z} dynamic | {z} static | {z} total' for z in SIZES)
              + ' |', '|---|' + '---|' * (3 * len(SIZES))]
        for v in METHODS:
            cells = []
            for z in SIZES:
                for key in ('dynamic_pj_per_flit', 'static_pj_per_flit', 'total_pj_per_flit'):
                    x, ref = mean(z, v, ld, key), mean(z, 'DeFT', ld, key)
                    cells.append(f'{x:.2f}' + ('' if v == 'DeFT' else f' ({100 * (x / ref - 1):+.1f})'))
            L.append(f'| {LABEL.get(v, v)} | ' + ' | '.join(cells) + ' |')
        L.append('')
    open(os.path.join(out, 'energy.md'), 'w', newline='\n').write('\n'.join(L) + '\n')
    fig, axes = plt.subplots(1, 2, figsize=(14, 4.6), sharey=True)
    w = 0.08
    for ax, ld in zip(axes, LOADS):
        for i, v in enumerate(METHODS):
            ys = [mean(z, v, ld, 'dynamic_pj_per_flit') for z in SIZES]
            ys2 = [mean(z, v, ld, 'static_pj_per_flit') for z in SIZES]
            xs = [j + (i - len(METHODS) / 2) * w for j in range(len(SIZES))]
            ax.bar(xs, ys, w * 0.95, label=LABEL.get(v, v), color=plt.cm.tab10(i))
            ax.bar(xs, ys2, w * 0.95, bottom=ys, color=plt.cm.tab10(i), alpha=0.35)
        ax.set_xticks(range(len(SIZES)))
        ax.set_xticklabels(SIZES)
        ax.set_title(f'uniform, {ld} x Lsat: energy per delivered flit (solid: dynamic, light: static)', fontsize=9)
        ax.set_ylabel('pJ per delivered flit')
        ax.grid(True, axis='y', color='#e6e5e1', lw=0.6)
    axes[0].legend(frameon=False, fontsize=7, ncol=2)
    fig.tight_layout()
    for ext in ('png', 'pdf'):
        fig.savefig(os.path.join(out, f'energy.{ext}'), dpi=125)
    plt.close(fig)
    print('\n'.join(L))


if __name__ == '__main__':
    stage = sys.argv[1]
    nproc = int(sys.argv[2]) if len(sys.argv) > 2 else 12
    os.makedirs(RES, exist_ok=True)
    if stage == 'energy':
        pc = powercheck(nproc)
        print('powercheck', pc, flush=True)
        rows = energy(nproc)
        report(rows, pc)
        sys.exit(0)
    raise SystemExit('unknown stage')
