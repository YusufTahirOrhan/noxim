"""Analysis of v8 step 5 (layer-weighted hop cost), following results_v8/PREREGISTRATION_step5.md.

Inputs (CSV only): results_v8/eval_runs.csv (CI_heurLA_G, CI_qlLA_G, FULL_qlLA_G), results_v6/eval_runs.csv
(DeFT_tm(rho*), CI_heurLA, CI_qlLA, FULL_qlLA; reused), results_v8/deft_runs.csv (DeFT(rho*), step 1),
results_v7/vlref_runs.csv and results_v8/vlref_runs.csv (VL counts of the references over all VLs).
Outputs (results_v8/report[_4x4]/): primary.csv, summary.md, effect_gamma.png
Usage: python3 report_v8.py [4x4]
"""
import csv
import math
import os
import sys

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt  # noqa: E402

from primary_from_csv import holm, ttest  # noqa: E402
from report_v4 import Data, load_csv, pct  # noqa: E402
import report_v5 as R5  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
R8 = os.path.join(HERE, 'results_v8')
PARENTS = ['CI_heurLA', 'CI_qlLA', 'FULL_qlLA']
G = [p + '_G' for p in PARENTS]
VS_REF = [(g, 'DeFT_tm') for g in G]
VS_PARENT = [(p + '_G', p) for p in PARENTS]
VS_DEFT = [(g, 'DeFT') for g in G] + [(p, 'DeFT') for p in PARENTS]
CONTEXT = [(p, 'DeFT_tm') for p in PARENTS]
METRICS = ['LAT', 'P99', 'THR']
SEEDS = range(31, 41)
COL = {'CI_heurLA': '#4a3aa7', 'CI_qlLA': '#1baf7a', 'FULL_qlLA': '#2a78d6'}


def main():
    sizes = ['4x4'] if len(sys.argv) > 1 and sys.argv[1] == '4x4' else ['3x3', '4x4']
    out = os.path.join(R8, 'report_4x4' if sizes == ['4x4'] else 'report')
    os.makedirs(out, exist_ok=True)
    new = load_csv(os.path.join(R8, 'eval_runs.csv'))
    R = {k: v for k, v in load_csv(os.path.join(HERE, 'results_v6', 'eval_runs.csv')).items()
         if k[0] in ['DeFT_tm'] + PARENTS}
    R.update(load_csv(os.path.join(R8, 'deft_runs.csv')))
    R.update(new)
    R = {k: v for k, v in R.items() if k[4] in SEEDS and k[1].split('-')[0] in sizes}
    D = {z: Data(R, R5.scen(z), R5.ladder, SEEDS) for z in sizes}
    n_new = sum(1 for k in new if k[1].split('-')[0] in sizes and k[4] in SEEDS)
    expected = sum(len(R5.ladder(p, m)) for z in sizes for p, m in R5.scen(z)) * len(G) * len(SEEDS)
    dead = sum(new[k]['dead'] for k in new if k[1].split('-')[0] in sizes)
    missing = [(v, p, m, r, s) for z in sizes for p, m in R5.scen(z) for r in R5.ladder(p, m) for s in SEEDS
               for v in G + PARENTS + ['DeFT_tm', 'DeFT'] if (v, p, m, r, s) not in R]

    prim = []
    for z in sizes:
        for a, b in VS_REF + VS_PARENT:
            for n in METRICS:
                xs = D[z].per_seed(a, b, n)
                e, lo, hi = pct(xs)
                prim.append(dict(size=z, variant=a, reference=b, metric=n, n_seeds=len(xs), effect_pct=round(e, 2),
                                 ci_low=round(lo, 2), ci_high=round(hi, 2), p=ttest(xs),
                                 capped_cells=D[z].capped(a, b) if n == 'THR' else 0))
    for x, q in zip(prim, holm([x['p'] for x in prim])):
        x['p_holm'] = q
        good = x['effect_pct'] > 0 if x['metric'] == 'THR' else x['effect_pct'] < 0
        x['verdict'] = ('better' if good else 'worse') if q < 0.05 else 'n.s.'
    with open(os.path.join(out, 'primary.csv'), 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(prim[0]), lineterminator='\n')
        w.writeheader()
        for x in prim:
            w.writerow({k: (f'{v:.4g}' if k in ('p', 'p_holm') else v) for k, v in x.items()})

    def row(a, b, z, sc=None):
        cells = []
        for n in METRICS:
            e, lo, hi = pct(D[z].per_seed(a, b, n, sc))
            cells.append(f'{e:+.2f} [{lo:+.2f}, {hi:+.2f}]')
        return f'| {z} | {a} vs {b} | ' + ' | '.join(cells) + ' |'

    L = [f'# v8 summary ({", ".join(sizes)}; seeds 31-40; generated by report_v8.py)', '',
         f'New runs (_G variants): {n_new} of {expected}; dead-end events: {dead}; missing cells in any comparison: '
         f'{len(missing)}. DeFT_tm(rho*) and the gamma = 1 parents from results_v6/eval_runs.csv; DeFT(rho*) from step 1.', '',
         f'## Primary results (pre-registered; Holm over {len(prim)} tests)', '',
         '| size | variant | reference | metric | effect % [95 % CI] | p (Holm) | verdict | THR capped cells |',
         '|---|---|---|---|---|---|---|---|']
    for x in prim:
        L.append(f'| {x["size"]} | {x["variant"]} | {x["reference"]} | {x["metric"]} | {x["effect_pct"]:+.2f} '
                 f'[{x["ci_low"]:+.2f}, {x["ci_high"]:+.2f}] | {x["p_holm"]:.3g} | **{x["verdict"]}** | '
                 f'{x["capped_cells"] if x["metric"] == "THR" else "-"} |')
    L += ['', '## Context: the gamma = 1 parents vs DeFT_tm(rho*) (v6 primary results, same runs)', '',
          '| size | comparison | LAT | P99 | THR |', '|---|---|---|---|---|']
    L += [row(a, b, z) for z in sizes for a, b in CONTEXT]
    L += ['', '## Secondary: against plain DeFT(rho*) (step 1 runs; unadjusted)', '',
          '| size | comparison | LAT | P99 | THR |', '|---|---|---|---|---|']
    L += [row(a, b, z) for z in sizes for a, b in VS_DEFT]
    L += ['', '## Secondary: saturation throughput without chipperm (unadjusted)', '',
          '| size | comparison | THR w/o chipperm |', '|---|---|---|']
    for z in sizes:
        sc = [s for s in R5.scen(z) if 'chipperm' not in s[0]]
        for a, b in VS_REF + VS_PARENT + VS_DEFT:
            e, lo, hi = pct(D[z].per_seed(a, b, 'THR', sc))
            L.append(f'| {z} | {a} vs {b} | {e:+.2f} [{lo:+.2f}, {hi:+.2f}] |')
    L.append('')
    for n in METRICS:
        L += [f'## Secondary: per-scenario {n} (unadjusted; `°` = CI excludes 0; `≥` = capped)', '']
        for z in sizes:
            sc = R5.scen(z)
            L += [f'**{z}**', '', '| comparison | ' + ' | '.join(f'{p.split("-")[1]} {m}' for p, m in sc) + ' |',
                  '|---|' + '---|' * len(sc)]
            for a, b in VS_PARENT + VS_REF + VS_DEFT[:3]:
                cells = []
                for p, m in sc:
                    e, lo, hi = pct(D[z].per_seed(a, b, n, [(p, m)]))
                    capped = n == 'THR' and any(D[z].thr(a, p, m, s)[1] or D[z].thr(b, p, m, s)[1] for s in SEEDS)
                    cells.append(f'{"≥" if capped else ""}{e:+.1f}{"°" if hi < 0 or lo > 0 else ""}')
                L.append(f'| {a} vs {b} | ' + ' | '.join(cells) + ' |')
            L.append('')
    vl = dict(load_csv(os.path.join(HERE, 'results_v7', 'vlref_runs.csv')))
    p8 = os.path.join(R8, 'vlref_runs.csv')
    if os.path.exists(p8):
        vl.update(load_csv(p8))
    vl.update(new)
    L += ['## Secondary: VL usage imbalance (max/mean over all functional VLs) at 1.0 x Lsat, mean over seeds', '',
          'All VLs (fixed computation). DeFT_tm(rho*) via its DEFT_LB proxy and CI_heurLA / CI_qlLA from '
          'results_v7/vlref_runs.csv; FULL_qlLA from results_v8/vlref_runs.csv; _G variants from their own runs.', '']
    for z in sizes:
        sc = R5.scen(z)
        L += [f'**{z}**', '', '| variant | ' + ' | '.join(f'{p.split("-")[1]} {m}' for p, m in sc) + ' |',
              '|---|' + '---|' * len(sc)]
        for v in ['DeFT_tm'] + [x for p in PARENTS for x in (p, p + '_G')]:
            cells = []
            for p, m in sc:
                r = R5.ladder(p, m)[3]
                xs = [vl[(v, p, m, r, s)]['imb'] for s in SEEDS if (v, p, m, r, s) in vl]
                xs = [x for x in xs if not math.isnan(x)]
                cells.append(f'{sum(xs) / len(xs):.2f}' if xs else 'n/a')
            L.append(f'| {v} | ' + ' | '.join(cells) + ' |')
        L.append('')
    if missing:
        L += ['## Missing cells', ''] + [f'- {m}' for m in missing[:50]] + ['']
    open(os.path.join(out, 'summary.md'), 'w', newline='\n').write('\n'.join(L) + '\n')

    fig, axes = plt.subplots(1, 3, figsize=(15, 4.6))
    for ax, n in zip(axes, METRICS):
        for j, z in enumerate(sizes):
            for k, par in enumerate(PARENTS):
                for q, (a, b, sty, lab) in enumerate(((par, 'DeFT_tm', 'o', f'{par} (gamma 1) vs DeFT_tm'),
                                                      (par + '_G', 'DeFT_tm', 's', f'{par}_G vs DeFT_tm'),
                                                      (par + '_G', par, 'D', f'{par}_G vs {par}'))):
                    e, lo, hi = pct(D[z].per_seed(a, b, n))
                    x = j * 5 + k * 1.5 + q * 0.4
                    ax.errorbar([x], [e], yerr=[[e - lo], [hi - e]], fmt=sty, color=COL[par], capsize=2, ms=6,
                                mfc='white' if q == 0 else COL[par], label=lab if j == 0 else None)
        ax.axhline(0, color='#52514e', lw=0.8)
        ax.set_xticks([j * 5 + 1.9 for j in range(len(sizes))])
        ax.set_xticklabels(sizes)
        ax.set_ylabel('% change, mean over scenarios (95 % CI)')
        ax.set_title({'LAT': 'Mean latency at 1.0 x Lsat (lower is better)', 'P99': 'p99 latency at 1.0 x Lsat',
                      'THR': 'Saturation throughput (higher is better)'}[n], fontsize=10)
        ax.grid(True, axis='y', color='#e6e5e1', lw=0.6)
        for sp in ('top', 'right'):
            ax.spines[sp].set_visible(False)
    h, lab = axes[0].get_legend_handles_labels()
    fig.legend(h, lab, loc='lower center', ncol=3, frameon=False, fontsize=8)
    fig.tight_layout(rect=(0, 0.16, 1, 1))
    fig.savefig(os.path.join(out, 'effect_gamma.png'), dpi=130)
    plt.close(fig)
    print(f'new runs {n_new}/{expected}, dead {dead}, missing {len(missing)}')
    for x in prim:
        print(x['size'], x['variant'], 'vs', x['reference'], x['metric'], x['effect_pct'], x['ci_low'], x['ci_high'],
              f'{x["p_holm"]:.3g}', x['verdict'])


if __name__ == '__main__':
    main()
