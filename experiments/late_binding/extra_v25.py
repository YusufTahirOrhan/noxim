"""v25: descriptive numbers that FINDINGS.md quotes and the tables of report_v25.py do not hold. Read only; no test.

Usage: python3 extra_v25.py [d] [e] [a]     (default: every part whose per-run CSV exists)
  d  app_runs.csv, pair_runs.csv   -> report/extra_D.md  (cases counted, the row with the lowest latency per trace, completion times)
  e  pipe0_runs.csv, eval_runs.csv -> report/extra_E.md  (the one-cycle router model next to the four-cycle model on the same four scenarios)
  a  addendum_runs.csv, eval_runs.csv -> report/extra_A.md  (the row with one residual cycle: cells, each reference row, beyond the peak)
The statistics are those of report_v25.py (imported): effect = 100 x (exp(mean per-seed log ratio) - 1), 95 % t interval over the seeds.
"""
import csv
import json
import math
import os
import sys

import report_v25 as R

NL = chr(10)
IDEAL = 'CI_heurLA_X'
ADD = 'CI_heurLA_X_LF1'


def gm(v):
    return math.exp(sum(math.log(x) for x in v) / len(v))


def rd(name):
    with open(os.path.join(R.RES, name), newline='') as f:
        return list(csv.DictReader(f))


def out(name, L):
    open(os.path.join(R.OUT, name), 'w', encoding='utf-8', newline=NL).write(NL.join(L) + NL)
    print(NL.join(L[:400]))


