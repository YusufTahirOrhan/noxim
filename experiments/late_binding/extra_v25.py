def part_d():
    main, second = R.MAIN, R.SECOND
    app, pair = rd('app_runs.csv'), rd('pair_runs.csv')
    L = ['# v25 Part D: extra descriptive numbers (generated by extra_v25.py from app_runs.csv and pair_runs.csv)', '',
         'Rows: %d single runs, %d pair runs. Relative values are per seed against DeFT_P of the same trace (or pair), mask and seed.' % (len(app), len(pair)), '']
    for name, rows in (('single', app), ('pairs', pair)):
        L.append('* %s: `finished` values %s; dead-end events %d; runs with injected != delivered: %d' % (
            name, sorted(set(r['finished'] for r in rows)), sum(int(float(r['dead_ends'])) for r in rows), sum(1 for r in rows if r['injected'] != r['delivered'])))
    A = {(r['benchmark'], r['method'], r['mask'], int(r['seed'])): r for r in app}
    benches = sorted(set(r['benchmark'] for r in app))
    masks = sorted(set(r['mask'] for r in app))
    methods = sorted(set(r['method'] for r in app))
    L += ['', '## One application', '',
          '| mask | trace | DeFT_P completion (cycles) | packets | main / DeFT_P latency (min..max over seeds) | second / DeFT_P | main - DeFT_P (cycles) | lowest mean latency (cycles) | main | second |',
          '|---|---|---|---|---|---|---|---|---|---|']
    tail = []
    for m in masks:
        n_lt = n_all = n_best = n_cells = 0
        for b in benches:
            seeds = sorted(s for (bb, me, mm, s) in A if bb == b and me == 'DeFT_P' and mm == m)
            lat = lambda me, s: float(A[(b, me, m, s)]['latency'])  # noqa: E731
            comp = [float(A[(b, 'DeFT_P', m, s)]['completion_cycles']) for s in seeds]
            rat = [lat(main, s) / lat('DeFT_P', s) for s in seeds]
            rat2 = [lat(second, s) / lat('DeFT_P', s) for s in seeds]
            dcyc = [lat(main, s) - lat('DeFT_P', s) for s in seeds]
            n_lt += sum(1 for x in rat if x < 1)
            n_all += len(rat)
            g = {me: gm([lat(me, s) for s in seeds]) for me in methods if (b, me, m, seeds[0]) in A}
            best = min(g, key=g.get)
            n_cells += 1
            n_best += best in (main, second)
            L.append('| %s | %s | %.0f | %s | %.3f..%.3f | %.3f..%.3f | %.2f..%.2f | %s (%.2f) | %.2f | %.2f |' % (
                m, b, sum(comp) / len(comp), A[(b, 'DeFT_P', m, seeds[0])]['packets'], min(rat), max(rat), min(rat2), max(rat2), min(dcyc), max(dcyc),
                best, g[best], g[main], g[second]))
        tail.append('* mask %s: the main row is below DeFT_P in %d of %d (trace, seed) cases; a late-binding row has the lowest mean latency on %d of %d traces' % (
            m, n_lt, n_all, n_best, n_cells))
    L += [''] + tail
    Pp = {(r['pair'], r['method'], r['mask'], int(r['s']), int(r['seed'])): r for r in pair}
    pairs = sorted(set(r['pair'] for r in pair))
    L += ['', '## Two applications', '',
          '| mask | compression | pair | DeFT_P completion (cycles) | main / DeFT_P latency (min..max over seeds) | completion | lowest mean latency | shortest completion |',
          '|---|---|---|---|---|---|---|---|']
    tail = []
    for m in masks:
        for c in (1, 2):
            n_lt = n_all = n_best = n_bestc = n_cells = 0
            cl = []
            for p in pairs:
                seeds = sorted(sd for (pp, me, mm, ss, sd) in Pp if pp == p and me == 'DeFT_P' and mm == m and ss == c)
                f = lambda me, sd, k: float(Pp[(p, me, m, c, sd)][k])  # noqa: E731
                comp = [f('DeFT_P', sd, 'completion_cycles') for sd in seeds]
                rat = [f(main, sd, 'latency') / f('DeFT_P', sd, 'latency') for sd in seeds]
                crat = [f(main, sd, 'completion_cycles') / f('DeFT_P', sd, 'completion_cycles') for sd in seeds]
                n_lt += sum(1 for x in rat if x < 1)
                n_all += len(rat)
                here = [me for me in methods if (p, me, m, c, seeds[0]) in Pp]
                g = {me: gm([f(me, sd, 'latency') for sd in seeds]) for me in here}
                gc = {me: gm([f(me, sd, 'completion_cycles') for sd in seeds]) for me in here}
                best, bestc = min(g, key=g.get), min(gc, key=gc.get)
                n_cells += 1
                n_best += best in (main, second)
                n_bestc += bestc in (main, second)
                cl.append(sum(comp) / len(comp))
                L.append('| %s | %d | %s | %.0f | %.3f..%.3f | %.4f..%.4f | %s | %s |' % (m, c, p, sum(comp) / len(comp), min(rat), max(rat), min(crat), max(crat), best, bestc))
            tail.append('* mask %s, compression %d: the main row is below DeFT_P in %d of %d (pair, seed) cases; a late-binding row has the lowest mean latency on %d '
                        'and the shortest completion on %d of %d pairs; DeFT_P completion %.0f..%.0f cycles' % (m, c, n_lt, n_all, n_best, n_bestc, n_cells, min(cl), max(cl)))
    L += [''] + tail + ['']
    out('extra_D.md', L)


