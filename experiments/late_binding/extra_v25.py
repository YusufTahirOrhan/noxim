def part_a():
    P = json.load(open(os.path.join(R.RES, 'load_points_v25.json')))
    dfile = os.path.join(R.RES, 'drops.json')
    dropped = json.load(open(dfile))['dropped'] if os.path.exists(dfile) else []
    ref_ff = [r for r in R.REF_FF if not (r == 'XY_SP' and 'xy_sp' in dropped)]

    def row_scen(row, z):
        sc = R.scen_b(z)
        if row in R.REF_FF:
            return [x for x in sc if not R.faulty(x[1])] if row in ref_ff else []
        if row in R.REF_FAULT:
            return [x for x in sc if R.faulty(x[1])]
        return sc

    def refs_of(z, sc):
        return R.REF_ALL + (R.REF_FAULT if R.faulty(sc[1]) else ref_ff)

    runs = R.load_runs(os.path.join(R.RES, 'eval_runs.csv'))
    runs.update(R.load_runs(os.path.join(R.RES, 'addendum_runs.csv')))
    D = R.Design(runs, P, 2, list(range(121, 131)), R.scen_b, row_scen, refs_of, R.IDX9)
    S = R.SIZES
    L = ['# v25 addendum: extra descriptive numbers for `CI_heurLA_X_LF1` (generated by extra_v25.py from addendum_runs.csv and eval_runs.csv)', '',
         'The Part B design (eight scenarios, seeds 121-130). Values are 2x2 / 3x3 / 4x4. No test beyond the family of `report/summary_A.md`.', '']
    L += ['## Y.1 Cells (one scenario on one size; 24): better / worse than the best baseline, 95 % interval excluding zero', '',
          '| row | THR better | worse | LAT better | worse | P99 better | worse |', '|---|---|---|---|---|---|---|']
    for row in (ADD, R.MAIN, R.DLY):
        c = [cells(D, row, R.scen_b, n) for n in R.METRICS]
        L.append('| %s | %s |' % (row, ' | '.join('%d of %d | %s' % (g, n, '; '.join(b) if b else '0') for g, b, n in c)))
    L += ['', '## Y.2 Against each reference row (over the scenarios both rows ran on; effect [95 % CI])', '', '| row | against | THR | LAT at 1.0 x Lsat | P99 |', '|---|---|---|---|---|']
    for row in (ADD, R.MAIN):
        for ref in R.REF_ALL + ref_ff + R.REF_FAULT:
            L.append('| %s | %s | %s |' % (row, ref, ' | '.join(' / '.join(R.eci(D.test(row, ref, z, row_scen(ref, z), n)) for z in S) for n in R.METRICS)))
    L += ['', '## Y.3 Scenarios the tuning saw (five) against those it did not (three): effect against the best baseline [95 % CI]', '',
          '| row | scenarios | THR | LAT at 1.0 x Lsat | P99 |', '|---|---|---|---|---|']
    for row in (ADD, R.MAIN):
        for label, keep in (('five seen', lambda sc: R.sname(sc) not in R.NEW), ('three not seen', lambda sc: R.sname(sc) in R.NEW)):
            L.append('| %s | %s | %s |' % (row, label, ' | '.join(' / '.join(R.eci(D.test(row, 'best', z, [sc for sc in R.scen_b(z) if keep(sc)], n)) for z in S) for n in R.METRICS)))
    L += ['', '## Y.4 Low-load latency against DeFT_P in cycles (mean over the eight scenarios of the difference of the seed means)', '',
          '| row | LAT at 0.2 x Lsat | LAT at 0.5 x Lsat |', '|---|---|---|']
    for row in (ADD, R.MAIN, R.DLY):
        L.append('| %s | %s |' % (row, ' | '.join(' / '.join('%+.2f' % R.mean(D.smean(row, z, sc, n) - D.smean('DeFT_P', z, sc, n) for sc in R.scen_b(z)) for z in S) for n in ('LAT02', 'LAT05'))))
