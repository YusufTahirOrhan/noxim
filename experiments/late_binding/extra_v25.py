def row_scen_e(row, z):
    return [x for x in R.scen_e(z) if not (row in ('MTR', 'RC') and R.faulty(x[1]))]


def refs_e(z, sc):
    return ['DeFT_P', 'DeFT_B'] + ([] if R.faulty(sc[1]) else ['MTR', 'RC'])


def cells(D, row, scen, name):
    """Number of (size, scenario) cells in which the row is better / worse than the best baseline (95 % interval excludes zero), and the worse ones."""
    good, bad, n = 0, [], 0
    for z in R.SIZES:
        for sc in scen(z):
            t = D.test(row, 'best', z, [sc], name)
            n += 1
            s = R.side(t)
            good += s > 0
            if s < 0:
                bad.append('%s %s %+.1f %% (%s)' % (z, R.sname(sc), t['effect_pct'], D.best(z, sc, name)))
    return good, bad, n


