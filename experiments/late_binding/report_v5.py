"""Analysis of v5 (tuned DeFT baseline), following results_v5/PREREGISTRATION.md.

Inputs (CSV only): results_v5/eval_runs.csv (make_eval_csv.py results_v5 eval), results_v5/load_points.json,
results_v5/tuning_choice.json; for the rho = 0.01 comparison results_v2/eval_runs.csv (2x2) and
results_v4/eval_runs.csv (3x3, 4x4).
Outputs (results_v5/report/): primary.csv, summary.md, effect_vs_size.png
Usage: python3 report_v5.py [first]
"""
import csv
import json
import math
import os
import sys

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt  # noqa: E402

from primary_from_csv import SCEN as SCEN_2X2, holm, ttest  # noqa: E402
from report_v4 import Data, load_csv, pct  # noqa: E402
import report_v4 as R4  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
R5 = os.path.join(HERE, 'results_v5')
LP = json.load(open(os.path.join(R5, 'load_points.json')))
CH = json.load(open(os.path.join(R5, 'tuning_choice.json')))
SIZES = ['2x2', '3x3', '4x4']
CHIPLETS = {'2x2': 4, '3x3': 9, '4x4': 16}
NORTH = {'2x2': '0x1111', '3x3': '0x111111111', '4x4': '0x1111111111111111'}
PRIMARY = [('CI_heur', 'DeFT_tm'), ('CI_heurLA', 'DeFT_tm'), ('CI_qlLA', 'DeFT_tm'), ('FULL_heurLA', 'DeFT_tm')]
ALT = [(v, 'DeFT') for v, _ in PRIMARY] + [('DeFT_tm', 'DeFT')]
METRICS = ['LAT', 'P99', 'THR']
CSTYLE = {'CI_heur': '#2a78d6', 'CI_heurLA': '#4a3aa7', 'CI_qlLA': '#1baf7a', 'FULL_heurLA': '#eb6834'}
TM_LUT_PATTERNS = ('hotspot', 'chipperm')


def scen(size):
    if size == '2x2':
        return [(f'2x2-{p}', m) for p, m in SCEN_2X2]
    return [(f'{size}-{p}', '0x0') for p in ('uniform', 'localized', 'hotspot', 'chipperm', 'movinghot')] + \
           [(f'{size}-{p}', NORTH[size]) for p in ('uniform', 'hotspot')]


def ladder(p, m):
    size, pat = p.split('-')
    return LP[f'{size}__{pat}__{m}']['eval']


def deft_differs(size, pattern):
    return CH[size]['DeFT'] != CH[size]['DeFT_tm'] or pattern in TM_LUT_PATTERNS


def main():
    first = len(sys.argv) > 1 and sys.argv[1] == 'first'
    seeds = range(21, 26) if first else range(21, 31)
    out = os.path.join(R5, 'report_seeds21-25' if first else 'report')
    os.makedirs(out, exist_ok=True)
    R = {k: v for k, v in load_csv(os.path.join(R5, 'eval_runs.csv')).items() if k[4] in seeds}
    # DeFT(rho*) where it is identical to DeFT_tm(rho*) (same LUT): reuse the DeFT_tm run
    for (v, p, m, r, s), x in list(R.items()):
        if v == 'DeFT_tm' and not deft_differs(p.split('-')[0], p.split('-')[1]):
            R.setdefault(('DeFT', p, m, r, s), x)
    D = {z: Data(R, scen(z), ladder, seeds) for z in SIZES}
    dead = sum(x['dead'] for x in R.values())

    # rho = 0.01 references: 2x2 from v2 (seeds 1-10, 11 scenarios), 3x3/4x4 from v4 (seeds 1-10)
    lp2 = json.load(open(os.path.join(HERE, 'results_v2', 'load_points.json')))
    v2 = Data(load_csv(os.path.join(HERE, 'results_v2', 'eval_runs.csv')), SCEN_2X2,
              lambda p, m: lp2[f'{p}__{m}']['eval'], range(1, 11))
    v4 = {z: Data(load_csv(os.path.join(HERE, 'results_v4', 'eval_runs.csv')), R4.scen(z), R4.ladder, range(1, 11))
          for z in ('3x3', '4x4')}
    old = {}
    for a, b in PRIMARY:
        for n in METRICS:
            old[('2x2', a, n)] = pct(v2.per_seed(a, b, n))
            for z in ('3x3', '4x4'):
                old[(z, a, n)] = pct(v4[z].per_seed(a, b, n))

    prim = []
    for z in SIZES:
        for a, b in PRIMARY:
            for n in METRICS:
                xs = D[z].per_seed(a, b, n)
                e, lo, hi = pct(xs)
                prim.append(dict(size=z, variant=a, reference=b, metric=n, n_seeds=len(xs), effect_pct=round(e, 2),
                                 ci_low=round(lo, 2), ci_high=round(hi, 2), p=ttest(xs),
                                 capped_cells=D[z].capped(a, b) if n == 'THR' else 0,
                                 rho01_effect_pct=round(old[(z, a, n)][0], 2)))
    for x, q in zip(prim, holm([x['p'] for x in prim])):
        x['p_holm'] = q
        good = x['effect_pct'] > 0 if x['metric'] == 'THR' else x['effect_pct'] < 0
        x['verdict'] = ('better' if good else 'worse') if q < 0.05 else 'n.s.'
    with open(os.path.join(out, 'primary.csv'), 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(prim[0]), lineterminator='\n')
        w.writeheader()
        for x in prim:
            w.writerow({k: (f'{v:.4g}' if k in ('p', 'p_holm') else v) for k, v in x.items()})

    L = [f'# v5 summary (seeds {min(seeds)}-{max(seeds)}; generated by report_v5.py)', '',
         f'rho*: ' + '; '.join(f'{z}: DeFT {CH[z]["DeFT"]}, DeFT_tm {CH[z]["DeFT_tm"]}' for z in SIZES) + '.',
         f'Runs: {len(R)} (including DeFT rows reused from identical DeFT_tm runs); dead-end events: {dead}.', '',
         '## Primary results (pre-registered; Holm over 36 tests)', '',
         'Effect: mean over the scenarios of a size (11 on 2x2, 7 on 3x3/4x4) of the per-seed log ratio vs DeFT_tm(rho*), '
         'as % change with a 95 % CI. "rho = 0.01" = the same comparison against DeFT_tm(rho = 0.01) in v2 (2x2) / v4 '
         '(3x3, 4x4), seeds 1-10, for context.', '',
         '| size | variant | metric | v5 effect % [95 % CI] | p (Holm) | verdict | THR capped cells | rho = 0.01 (v2/v4) |',
         '|---|---|---|---|---|---|---|---|']
    for x in prim:
        L.append(f'| {x["size"]} | {x["variant"]} | {x["metric"]} | {x["effect_pct"]:+.2f} [{x["ci_low"]:+.2f}, '
                 f'{x["ci_high"]:+.2f}] | {x["p_holm"]:.3g} | **{x["verdict"]}** | '
                 f'{x["capped_cells"] if x["metric"] == "THR" else "-"} | {x["rho01_effect_pct"]:+.2f} |')
    L.append('')

    L += ['## Secondary: DeFT(rho*) (uniform LUT, no traffic knowledge) as the reference (unadjusted 95 % CI)', '',
          '| size | variant | LAT 1.0 | P99 1.0 | THR |', '|---|---|---|---|---|']
    for z in SIZES:
        for a, b in ALT:
            cells = [pct(D[z].per_seed(a, b, n)) for n in METRICS]
            L.append(f'| {z} | {a} vs {b} | ' + ' | '.join(f'{c[0]:+.1f} [{c[1]:+.1f}, {c[2]:+.1f}]' for c in cells) + ' |')
    L.append('')

    L += ['## Secondary: saturation throughput without chipperm (unadjusted)', '', '| size | variant | THR w/o chipperm |',
          '|---|---|---|']
    for z in SIZES:
        sc = [s for s in scen(z) if 'chipperm' not in s[0]]
        for a, b in PRIMARY:
            e, lo, hi = pct(D[z].per_seed(a, b, 'THR', sc))
            L.append(f'| {z} | {a} vs {b} | {e:+.2f} [{lo:+.2f}, {hi:+.2f}] |')
    L.append('')

    for n in METRICS:
        L += [f'## Secondary: per-scenario {n} vs DeFT_tm(rho*) (unadjusted; `°` = CI excludes 0; `≥` = capped)', '']
        for z in SIZES:
            sc = scen(z)
            L += [f'**{z}**', '', '| variant | ' + ' | '.join(f'{p.split("-")[1]} {m}' for p, m in sc) + ' |',
                  '|---|' + '---|' * len(sc)]
            for a, b in PRIMARY + [('DeFT', 'DeFT_tm')]:
                cells = []
                for p, m in sc:
                    e, lo, hi = pct(D[z].per_seed(a, b, n, [(p, m)]))
                    capped = n == 'THR' and any(D[z].thr(a, p, m, s)[1] or D[z].thr(b, p, m, s)[1] for s in seeds)
                    cells.append(f'{"≥" if capped else ""}{e:+.1f}{"°" if hi < 0 or lo > 0 else ""}')
                L.append(f'| {a} | ' + ' | '.join(cells) + ' |')
            L.append('')

    L += ['## Secondary: VL usage imbalance (max/mean over functional VLs) at ~1.0 x Lsat, mean over seeds', '',
          'DeFT_tm(rho*) from the traffic-identical proxy.', '']
    for z in SIZES:
        sc = scen(z)
        L += [f'**{z}**', '', '| variant | ' + ' | '.join(f'{p.split("-")[1]} {m}' for p, m in sc) + ' |',
              '|---|' + '---|' * len(sc)]
        for v in ('DeFT_tm', 'CI_heur', 'CI_heurLA', 'CI_qlLA', 'FULL_heurLA'):
            cells = []
            for p, m in sc:
                xs = [R[(v, p, m, ladder(p, m)[3], s)]['imb'] for s in seeds if (v, p, m, ladder(p, m)[3], s) in R]
                xs = [x for x in xs if not math.isnan(x)]
                cells.append(f'{sum(xs) / len(xs):.2f}' if xs else 'n/a')
            L.append(f'| {v} | ' + ' | '.join(cells) + ' |')
        L.append('')
    open(os.path.join(out, 'summary.md'), 'w', newline='\n').write('\n'.join(L) + '\n')

    # ---- figure: effects vs size, rho = 0.01 (v2/v4) and rho* (v5) side by side ----
    fig, axes = plt.subplots(1, 3, figsize=(16, 4.8))
    titles = {'LAT': 'Mean latency at 1.0 x Lsat (lower is better)', 'P99': 'p99 latency at 1.0 x Lsat (lower is better)',
              'THR': 'Saturation throughput (higher is better)'}
    for ax, n in zip(axes, METRICS):
        for j, (a, b) in enumerate(PRIMARY):
            col = CSTYLE[a]
            off = (j - 1.5) * 0.22
            xo = [CHIPLETS[z] + off - 0.11 for z in SIZES]
            yo = [old[(z, a, n)] for z in SIZES]
            ax.errorbar(xo, [y[0] for y in yo], yerr=[[y[0] - y[1] for y in yo], [y[2] - y[0] for y in yo]],
                        fmt='o:', mfc='white', color=col, capsize=2, ms=5, lw=1)
            pts = [x for x in prim if x['variant'] == a and x['metric'] == n]
            xn = [CHIPLETS[x['size']] + off + 0.11 for x in pts]
            ax.errorbar(xn, [x['effect_pct'] for x in pts],
                        yerr=[[x['effect_pct'] - x['ci_low'] for x in pts], [x['ci_high'] - x['effect_pct'] for x in pts]],
                        fmt='o-', color=col, capsize=2, ms=6, lw=1.6, label=f'{a} vs DeFT_tm')
        ax.axhline(0, color='#52514e', lw=0.8)
        ax.set_xticks([4, 9, 16])
        ax.set_xticklabels(['4 (2x2)', '9 (3x3)', '16 (4x4)'])
        ax.set_xlabel('chiplets')
        ax.set_ylabel('% change vs DeFT_tm, mean over scenarios')
        ax.set_title(titles[n], fontsize=10)
        ax.grid(True, axis='y', color='#e6e5e1', lw=0.6)
        for sp in ('top', 'right'):
            ax.spines[sp].set_visible(False)
    h, lab = axes[0].get_legend_handles_labels()
    fig.legend(h, lab, loc='lower center', ncol=4, frameon=False, fontsize=9)
    fig.suptitle('Primary effects vs system size. Hollow markers, dotted: reference DeFT_tm with rho = 0.01 (v2 / v4, '
                 'seeds 1-10). Filled, solid: reference DeFT_tm with tuned rho* (v5, seeds 21-30). 95 % CI over seeds.',
                 fontsize=9)
    fig.tight_layout(rect=(0, 0.07, 1, 1))
    fig.savefig(os.path.join(out, 'effect_vs_size.png'), dpi=130)
    plt.close(fig)
    print(f'runs {len(R)}, dead {dead}')
    for x in prim:
        print(x['size'], x['variant'], x['metric'], x['effect_pct'], x['ci_low'], x['ci_high'], f'{x["p_holm"]:.3g}',
              x['verdict'], 'rho0.01:', x['rho01_effect_pct'])


if __name__ == '__main__':
    main()
