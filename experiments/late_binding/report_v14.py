"""v14 (Part F2) analysis, following results_v14_faultload/PREREGISTRATION.md.

Input: results_v14_faultload/eval_runs.csv (make_eval_csv.py results_v14_faultload eval), load_choice.json,
results_v11/masks.json. Outputs (results_v14_faultload/report/): primary.csv, secondary.csv, summary.md,
fault_load.{png,pdf}
"""
import csv
import json
import math
import os

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt  # noqa: E402

from primary_from_csv import ci, holm, ttest  # noqa: E402
from report_v4 import load_csv  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
R14 = os.path.join(HERE, 'results_v14_faultload')
SIZES = ['2x2', '3x3', '4x4']
KS = [1, 2, 3]
PATTERNS = ['uniform', 'hotspot']
SEEDS = range(53, 58)
METHODS = ['DeFT', 'DeFT_Dis', 'DeFT_Ran', 'XY_SP', 'DeFT_OE_G', 'CI_heurLA_G', 'CI_qlLA_G', 'FULL_qlLA_G']
OURS = ['CI_qlLA_G', 'FULL_qlLA_G']
LABEL = {'DeFT': 'DeFT(rho*)', 'DeFT_Dis': 'DeFT-Dis', 'DeFT_Ran': 'DeFT-Ran', 'XY_SP': 'XY-SP'}
COL = {'DeFT': '#52514e', 'DeFT_Dis': '#8e8d87', 'DeFT_Ran': '#b9b7af', 'XY_SP': '#6b5b95', 'DeFT_OE_G': '#e0a800',
       'CI_heurLA_G': '#4a3aa7', 'CI_qlLA_G': '#1baf7a', 'FULL_qlLA_G': '#2a78d6'}


def main():
    out = os.path.join(R14, 'report')
    os.makedirs(out, exist_ok=True)
    R = load_csv(os.path.join(R14, 'eval_runs.csv'))
    ch = json.load(open(os.path.join(R14, 'load_choice.json')))
    ms = {k: v[:5] for k, v in json.load(open(os.path.join(HERE, 'results_v11', 'masks.json'))).items()}

    def val(v, z, k, p, m, s, name):
        x = R[(v, f'{z}-{p}', m, ch[f'{z}__k{k}__{p}']['rate'], s)]
        return x['p99'] if name == 'P99' else x['latency']

    def units(a, b, z, k, name):
        us = []
        for m in ms[f'{z}__k{k}']:
            for s in SEEDS:
                try:
                    us.append(sum(math.log(val(a, z, k, p, m, s, name) / val(b, z, k, p, m, s, name))
                                  for p in PATTERNS) / 2)
                except KeyError:
                    pass
        return us

    def row(a, b, z, k, name):
        us = units(a, b, z, k, name)
        mu, h = ci(us)
        return dict(size=z, k=k, variant=a, reference=b, metric=name, n_units=len(us),
                    effect_pct=round(100 * (math.exp(mu) - 1), 2), ci_low=round(100 * (math.exp(mu - h) - 1), 2),
                    ci_high=round(100 * (math.exp(mu + h) - 1), 2), p=ttest(us))

    def geo(v, z, k, name):
        xs = [math.log(val(v, z, k, p, m, s, name)) for m in ms[f'{z}__k{k}'] for s in SEEDS for p in PATTERNS
              if (v, f'{z}-{p}', m, ch[f'{z}__k{k}__{p}']['rate'], s) in R]
        return math.exp(sum(xs) / len(xs))

    expected = 3 * 3 * 5 * 2 * len(METHODS) * len(SEEDS)
    present = sum(1 for z in SIZES for k in KS for m in ms[f'{z}__k{k}'] for p in PATTERNS for v in METHODS
                  for s in SEEDS if (v, f'{z}-{p}', m, ch[f'{z}__k{k}__{p}']['rate'], s) in R)
    dead = sum(x['dead'] for x in R.values())
    prim = [row(a, 'DeFT', z, k, 'LAT') for z in SIZES for k in KS for a in OURS]
    for x, q in zip(prim, holm([x['p'] for x in prim])):
        x['p_holm'] = q
        x['verdict'] = ('ours better' if x['effect_pct'] < 0 else 'ours worse') if q < 0.05 else 'n.s.'
    sec = [row(v, 'DeFT', z, k, n) for z in SIZES for k in KS for v in METHODS if v != 'DeFT' for n in ('LAT', 'P99')]
    for path, rows in (('primary.csv', prim), ('secondary.csv', sec)):
        with open(os.path.join(out, path), 'w', newline='') as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator='\n')
            w.writeheader()
            for x in rows:
                w.writerow({kk: (f'{v:.4g}' if kk in ('p', 'p_holm') else v) for kk, v in x.items()})

    def fmt(x, key='p'):
        return f'{x["effect_pct"]:+.1f} [{x["ci_low"]:+.1f}, {x["ci_high"]:+.1f}] ({key.replace("_", " ")} {x[key]:.2g})'
    sup = sum(x['verdict'] == 'ours better' for x in prim)
    against = sum(x['verdict'] == 'ours worse' for x in prim)
    L = ['# v14 summary: fault sweep below the faulty saturation point (seeds 53-57; generated by report_v14.py)', '',
         f'Runs: {present} of {expected}; dead-end events: {dead}.', '',
         '## Primary (Holm over 18): mean latency at the F1 test load vs DeFT(rho*)', '',
         'Unit = (mask, seed), mean over uniform and hotspot of the log ratio; 25 units.', '',
         '| size | k | test load uniform / hotspot (x fault-free Lsat) | CI_qlLA_G | FULL_qlLA_G |', '|---|---|---|---|---|']
    for z in SIZES:
        for k in KS:
            c = [next(x for x in prim if (x['size'], x['k'], x['variant']) == (z, k, a)) for a in OURS]
            lu, lh = ch[f'{z}__k{k}__uniform'], ch[f'{z}__k{k}__hotspot']
            L.append(f'| {z} | {k} | {lu["rate"]} ({lu["mult"]}) / {lh["rate"]} ({lh["mult"]}) | ' +
                     ' | '.join(f'{fmt(x, "p_holm")} **{x["verdict"]}**' for x in c) + ' |')
    L += ['', f'Supported: {sup} of 18; significant against ours: {against}.', '',
          '## Secondary: P99 and all methods vs DeFT(rho*) (unadjusted)', '',
          '| size | k | method | LAT | P99 |', '|---|---|---|---|---|']
    for z in SIZES:
        for k in KS:
            for v in METHODS[1:]:
                c = [next(x for x in sec if (x['size'], x['k'], x['variant'], x['metric']) == (z, k, v, n))
                     for n in ('LAT', 'P99')]
                L.append(f'| {z} | {k} | {LABEL.get(v, v)} | {fmt(c[0])} | {fmt(c[1])} |')
    L += ['', '## Geometric-mean latency at the test load (cycles) and saturated cells (accepted < 95 % of offered)', '',
          '| size | k | ' + ' | '.join(LABEL.get(v, v) for v in METHODS) + ' |', '|---|---|' + '---|' * len(METHODS)]
    for z in SIZES:
        for k in KS:
            cells = []
            for v in METHODS:
                n = t = 0
                for m in ms[f'{z}__k{k}']:
                    for s in SEEDS:
                        for p in PATTERNS:
                            r = ch[f'{z}__k{k}__{p}']['rate']
                            x = R.get((v, f'{z}-{p}', m, r, s))
                            if x:
                                t += 1
                                n += x['accepted'] < 0.95 * 8 * r
                cells.append(f'{geo(v, z, k, "LAT"):.1f} ({n}/{t} sat.)')
            L.append(f'| {z} | {k} | ' + ' | '.join(cells) + ' |')
    open(os.path.join(out, 'summary.md'), 'w', newline='\n').write('\n'.join(L) + '\n')
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.6))
    for ax, z in zip(axes, SIZES):
        for v in METHODS:
            ax.plot(KS, [geo(v, z, k, 'LAT') for k in KS], marker='o', color=COL[v], lw=2.2 if v in OURS else 1.2,
                    ls='-' if v in OURS or v == 'DeFT' else '--', label=LABEL.get(v, v))
        ax.set_xticks(KS)
        ax.set_xlabel('faulty VLs per chiplet (k)')
        ax.set_ylabel('mean latency at the test load (cycles)')
        ax.set_title(f'{z}', fontsize=10)
        ax.grid(True, color='#e6e5e1', lw=0.6)
        for sp in ('top', 'right'):
            ax.spines[sp].set_visible(False)
    h, lab = axes[0].get_legend_handles_labels()
    fig.legend(h, lab, loc='lower center', ncol=8, frameon=False, fontsize=8)
    fig.suptitle('Latency below the faulty saturation point (load per (size, k, pattern) from F1); geometric mean over '
                 '5 masks x 5 seeds x {uniform, hotspot}', fontsize=10)
    fig.tight_layout(rect=(0, 0.08, 1, 0.94))
    for ext in ('png', 'pdf'):
        fig.savefig(os.path.join(out, f'fault_load.{ext}'), dpi=125)
    plt.close(fig)
    print(f'runs {present}/{expected}, dead {dead}; supported {sup}/18, against {against}')
    for x in prim:
        print(x['size'], x['k'], x['variant'], x['effect_pct'], x['ci_low'], x['ci_high'], f'{x["p_holm"]:.3g}', x['verdict'])


if __name__ == '__main__':
    main()
