"""Analysis of v7 (bounded-deviation entry), following results_v7/PREREGISTRATION.md.

Inputs (CSV only): results_v7/eval_runs.csv (CI_heurLA_B, CI_qlLA_B; make_eval_csv.py results_v7 eval),
results_v6/eval_runs.csv (DeFT_tm(rho*), CI_heurLA, CI_qlLA; reused, the simulator being deterministic),
results_v7/vlref_runs.csv (VL counts at 1.0 x Lsat of the references, re-run because of the v4-v6 VL imbalance bug),
results_v5/load_points.json.
Outputs (results_v7/report[_4x4]/): primary.csv, summary.md, effect_bound.png
Usage: python3 report_v7.py [4x4]
"""
import csv
import math
import os
import sys

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt  # noqa: E402

from primary_from_csv import holm, ttest  # noqa: E402
from report_v4 import Data, load_csv, pct  # noqa: E402
import report_v5 as R5  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
R7 = os.path.join(HERE, 'results_v7')
R6 = os.path.join(HERE, 'results_v6')
VS_REF = [('CI_heurLA_B', 'DeFT_tm'), ('CI_qlLA_B', 'DeFT_tm')]
VS_PARENT = [('CI_heurLA_B', 'CI_heurLA'), ('CI_qlLA_B', 'CI_qlLA')]
CONTEXT = [('CI_heurLA', 'DeFT_tm'), ('CI_qlLA', 'DeFT_tm')]      # v6 primary results, for reference
METRICS = ['LAT', 'P99', 'THR']
SEEDS = range(31, 41)


def main():
    sizes = ['4x4'] if len(sys.argv) > 1 and sys.argv[1] == '4x4' else ['3x3', '4x4']
    out = os.path.join(R7, 'report_4x4' if sizes == ['4x4'] else 'report')
    os.makedirs(out, exist_ok=True)
    R7runs = load_csv(os.path.join(R7, 'eval_runs.csv'))
    R6runs = {k: v for k, v in load_csv(os.path.join(R6, 'eval_runs.csv')).items()
              if k[0] in ('DeFT_tm', 'CI_heurLA', 'CI_qlLA')}
    R = dict(R6runs)
    R.update(R7runs)
    R = {k: v for k, v in R.items() if k[4] in SEEDS and k[1].split('-')[0] in sizes}
    D = {z: Data(R, R5.scen(z), R5.ladder, SEEDS) for z in sizes}
    n7 = sum(1 for k in R7runs if k[1].split('-')[0] in sizes and k[4] in SEEDS)
    expected = sum(len(R5.ladder(p, m)) for z in sizes for p, m in R5.scen(z)) * 2 * len(SEEDS)
    dead = sum(R7runs[k]['dead'] for k in R7runs if k[1].split('-')[0] in sizes)
    missing = []
    for z in sizes:
        for p, m in R5.scen(z):
            for r in R5.ladder(p, m):
                for v in ('CI_heurLA_B', 'CI_qlLA_B', 'DeFT_tm', 'CI_heurLA', 'CI_qlLA'):
                    missing += [(v, p, m, r, s) for s in SEEDS if (v, p, m, r, s) not in R]

    prim = []
    for z in sizes:
        for a, b in VS_REF + VS_PARENT:
            for n in METRICS:
                xs = D[z].per_seed(a, b, n)
                e, lo, hi = pct(xs)
                prim.append(dict(size=z, variant=a, reference=b, metric=n, n_seeds=len(xs), effect_pct=round(e, 2),
                                 ci_low=round(lo, 2), ci_high=round(hi, 2), p=ttest(xs),
                                 capped_cells=D[z].capped(a, b) if n == 'THR' else 0))
    for x, q in zip(prim, holm([x['p'] for x in prim])):
        x['p_holm'] = q
        good = x['effect_pct'] > 0 if x['metric'] == 'THR' else x['effect_pct'] < 0
        x['verdict'] = ('better' if good else 'worse') if q < 0.05 else 'n.s.'
    with open(os.path.join(out, 'primary.csv'), 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(prim[0]), lineterminator='\n')
        w.writeheader()
        for x in prim:
            w.writerow({k: (f'{v:.4g}' if k in ('p', 'p_holm') else v) for k, v in x.items()})

    L = [f'# v7 summary ({", ".join(sizes)}; seeds 31-40; generated by report_v7.py)', '',
         f'New runs (CI_heurLA_B, CI_qlLA_B): {n7} of {expected}; dead-end events: {dead}; missing cells in any '
         f'comparison: {len(missing)}. DeFT_tm(rho*), CI_heurLA and CI_qlLA are the v6 runs (results_v6/eval_runs.csv).', '',
         f'## Primary results (pre-registered; Holm over {len(prim)} tests)', '',
         'Effect: mean over the 7 scenarios of the size of the per-seed log ratio, % change, 95 % CI over seeds 31-40.', '',
         '| size | variant | reference | metric | effect % [95 % CI] | p (Holm) | verdict | THR capped cells |',
         '|---|---|---|---|---|---|---|---|']
    for x in prim:
        L.append(f'| {x["size"]} | {x["variant"]} | {x["reference"]} | {x["metric"]} | {x["effect_pct"]:+.2f} '
                 f'[{x["ci_low"]:+.2f}, {x["ci_high"]:+.2f}] | {x["p_holm"]:.3g} | **{x["verdict"]}** | '
                 f'{x["capped_cells"] if x["metric"] == "THR" else "-"} |')
    L.append('')
    L += ['## Context: the unbounded parents vs DeFT_tm(rho*) (v6 primary results, same runs)', '',
          '| size | comparison | LAT | P99 | THR |', '|---|---|---|---|---|']
    for z in sizes:
        for a, b in CONTEXT:
            cells = []
            for n in METRICS:
                e, lo, hi = pct(D[z].per_seed(a, b, n))
                cells.append(f'{e:+.2f} [{lo:+.2f}, {hi:+.2f}]')
            L.append(f'| {z} | {a} vs {b} | ' + ' | '.join(cells) + ' |')
    L.append('')

    L += ['## Secondary: saturation throughput without chipperm (unadjusted)', '', '| size | comparison | THR w/o chipperm |',
          '|---|---|---|']
    for z in sizes:
        sc = [s for s in R5.scen(z) if 'chipperm' not in s[0]]
        for a, b in VS_REF + VS_PARENT + CONTEXT:
            e, lo, hi = pct(D[z].per_seed(a, b, 'THR', sc))
            L.append(f'| {z} | {a} vs {b} | {e:+.2f} [{lo:+.2f}, {hi:+.2f}] |')
    L.append('')

    for n in METRICS:
        L += [f'## Secondary: per-scenario {n} (unadjusted; `°` = CI excludes 0; `≥` = capped)', '']
        for z in sizes:
            sc = R5.scen(z)
            L += [f'**{z}**', '', '| comparison | ' + ' | '.join(f'{p.split("-")[1]} {m}' for p, m in sc) + ' |',
                  '|---|' + '---|' * len(sc)]
            for a, b in VS_REF + VS_PARENT + CONTEXT:
                cells = []
                for p, m in sc:
                    e, lo, hi = pct(D[z].per_seed(a, b, n, [(p, m)]))
                    capped = n == 'THR' and any(D[z].thr(a, p, m, s)[1] or D[z].thr(b, p, m, s)[1] for s in SEEDS)
                    cells.append(f'{"≥" if capped else ""}{e:+.1f}{"°" if hi < 0 or lo > 0 else ""}')
                L.append(f'| {a} vs {b} | ' + ' | '.join(cells) + ' |')
            L.append('')

    # candidate counts and VL imbalance
    cand = load_cand()
    vlr = load_csv(os.path.join(R7, 'vlref_runs.csv')) if os.path.exists(os.path.join(R7, 'vlref_runs.csv')) else {}
    L += ['## Secondary: entry candidates after bounding (mean over seeds; 4 = unbounded fault-free, 3 = one faulty VL '
          'per chiplet)', '']
    for z in sizes:
        sc = R5.scen(z)
        L += [f'**{z}**', '', '| variant | load | ' + ' | '.join(f'{p.split("-")[1]} {m}' for p, m in sc) + ' |',
              '|---|---|' + '---|' * len(sc)]
        for v in ('CI_heurLA_B', 'CI_qlLA_B'):
            for i, lab in ((1, '~0.5'), (3, '1.0'), (6, '1.6')):
                cells = []
                for p, m in sc:
                    xs = [cand[(v, p, m, R5.ladder(p, m)[i], s)] for s in SEEDS if (v, p, m, R5.ladder(p, m)[i], s) in cand]
                    cells.append(f'{sum(xs) / len(xs):.2f}' if xs else 'n/a')
                L.append(f'| {v} | {lab} x Lsat | ' + ' | '.join(cells) + ' |')
        L.append('')
    L += ['## Secondary: VL usage imbalance (max/mean over all functional VLs) at 1.0 x Lsat, mean over seeds', '',
          'Computed over **all** VLs (the v4-v6 column covered VL ids 0-15 only; see DECISIONS.md). DeFT_tm(rho*) from its '
          'traffic-identical DEFT_LB proxy; DeFT_tm, CI_heurLA and CI_qlLA from the `vlref` re-runs.', '']
    for z in sizes:
        sc = R5.scen(z)
        L += [f'**{z}**', '', '| variant | ' + ' | '.join(f'{p.split("-")[1]} {m}' for p, m in sc) + ' |',
              '|---|' + '---|' * len(sc)]
        for v in ('DeFT_tm', 'CI_heurLA', 'CI_qlLA', 'CI_heurLA_B', 'CI_qlLA_B'):
            src = R7runs if v.endswith('_B') else vlr
            cells = []
            for p, m in sc:
                r = R5.ladder(p, m)[3]
                xs = [src[(v, p, m, r, s)]['imb'] for s in SEEDS if (v, p, m, r, s) in src]
                xs = [x for x in xs if not math.isnan(x)]
                cells.append(f'{sum(xs) / len(xs):.2f}' if xs else 'n/a')
            L.append(f'| {v} | ' + ' | '.join(cells) + ' |')
        L.append('')
    if missing:
        L += ['## Missing cells', ''] + [f'- {m}' for m in missing[:50]] + ['']
    open(os.path.join(out, 'summary.md'), 'w', newline='\n').write('\n'.join(L) + '\n')

    # figure: effects of the bound (vs parent) and of the bounded variants vs DeFT_tm, per size
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.6))
    col = {'CI_heurLA': '#4a3aa7', 'CI_qlLA': '#1baf7a'}
    for ax, n in zip(axes, METRICS):
        xt = []
        for j, z in enumerate(sizes):
            for k, par in enumerate(('CI_heurLA', 'CI_qlLA')):
                for q, (a, b, sty, lab) in enumerate(((par, 'DeFT_tm', 'o:', f'{par} (unbounded) vs DeFT_tm'),
                                                      (par + '_B', 'DeFT_tm', 's-', f'{par}_B vs DeFT_tm'),
                                                      (par + '_B', par, 'D--', f'{par}_B vs {par}'))):
                    e, lo, hi = pct(D[z].per_seed(a, b, n))
                    x = j * 4 + k * 1.6 + q * 0.45
                    ax.errorbar([x], [e], yerr=[[e - lo], [hi - e]], fmt=sty[0], color=col[par], capsize=2, ms=6,
                                mfc='white' if q == 0 else col[par], label=lab if j == 0 else None)
            xt.append((j * 4 + 1.25, z))
        ax.axhline(0, color='#52514e', lw=0.8)
        ax.set_xticks([x for x, _ in xt])
        ax.set_xticklabels([f'{z}' for _, z in xt])
        ax.set_ylabel('% change, mean over scenarios (95 % CI)')
        ax.set_title({'LAT': 'Mean latency at 1.0 x Lsat (lower is better)', 'P99': 'p99 latency at 1.0 x Lsat',
                      'THR': 'Saturation throughput (higher is better)'}[n], fontsize=10)
        ax.grid(True, axis='y', color='#e6e5e1', lw=0.6)
        for sp in ('top', 'right'):
            ax.spines[sp].set_visible(False)
    h, lab = axes[0].get_legend_handles_labels()
    fig.legend(h, lab, loc='lower center', ncol=3, frameon=False, fontsize=8)
    fig.tight_layout(rect=(0, 0.12, 1, 1))
    fig.savefig(os.path.join(out, 'effect_bound.png'), dpi=130)
    plt.close(fig)
    print(f'new runs {n7}/{expected}, dead {dead}, missing {len(missing)}')
    for x in prim:
        print(x['size'], x['variant'], 'vs', x['reference'], x['metric'], x['effect_pct'], x['ci_low'], x['ci_high'],
              f'{x["p_holm"]:.3g}', x['verdict'])


def load_cand():
    out = {}
    path = os.path.join(R7, 'eval_cand.csv')
    if os.path.exists(path):
        for r in csv.DictReader(open(path)):
            out[(r['variant'], r['pattern'], r['mask'], float(r['rate']), int(r['seed']))] = float(r['entry_candidates_after_mean'])
    return out


if __name__ == '__main__':
    main()
